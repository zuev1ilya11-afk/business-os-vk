"""Build a frontend-only delta over the immutable, RU-compatible PR297 package."""
import copy
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import zipfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
BASE = '1ff029deaaa08d2d0181fea1826f912b47b19280'
SOURCE = 'b717ec10104d52ab664cd2c29de1e31789c96e00'
BASE_PACKAGE_SHA = '3fa6b44e695441a8bda6446cbe6058394feedd9b51113f36d34c39386a8daec3'
BEFORE = 'cc4fa850b12dadd27370'
PREFIX = b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD='
SOURCES = ['master-order-hands-layout-v72.js', 'master-order-actions-v179.js',
           'contact-status.js', 'master-help-entry.js', 'master-order-focus-v126.js',
           'approved-master-ui.css']

def sha(data):
    return hashlib.sha256(data).hexdigest()

def source(rev, name):
    return subprocess.check_output(['git', 'show', rev+':'+name], cwd=ROOT)

def ru(data):
    return data.replace(b'https://obsropbslfwtanyspjbi.supabase.co', b'https://139.100.237.167').replace(
        b'https://business-os-api-gateway.netlify.app', b'https://139.100.237.167')

def module_bounds(bundle, name):
    marker = b'// Source: '+name.encode()+b'\n'
    assert bundle.count(marker) == 1, name
    start = bundle.index(marker)+len(marker)
    end = bundle.find(b'\n;\n// Source:', start)
    if end < 0:
        assert bundle.endswith(b'\n;\n')
        end = len(bundle)-3
    return start, end

def prepare(previous):
    assert sha(previous.read_bytes()) == BASE_PACKAGE_SHA, 'Wrong PR297 package'
    with zipfile.ZipFile(previous) as z:
        prior = json.loads(z.read('release.json'))
        old = {n: z.read('payload/'+n) for n in prior['after']}
    meta = json.loads(old['build-version.js'][len(PREFIX):-2])
    assert meta['id'] == BEFORE
    for name, data in old.items():
        assert sha(data) == prior['after'][name]
    before_hashes = {**prior['before'], **prior['after']}
    new, optional, optional_meta = {}, {}, {}
    bundle = old['startup-shell.bundle.js']
    for name in SOURCES:
        before, after = ru(source(BASE, name)), ru(source(SOURCE, name))
        container = meta.get('assetBundles', {}).get(name)
        if container:
            assert container == 'startup-shell.bundle.js'
            start, end = module_bounds(bundle, name)
            body = bundle[start:end]
            if name == 'master-help-entry.js':
                # Retain the newer RU help editor, close guards and viewport fixes.
                a = b"if(card)add(card,'home',"
                b = b"if(card)add(card.querySelector('.bosOrderExtraActions')||card,'home',"
                assert before.count(a) == 1 and before.replace(a, b) == after
                assert body.count(a) == 1
                before, after = body.rstrip()+b'\n', body.replace(a, b).rstrip()+b'\n'
            else:
                assert body.rstrip() == before.rstrip(), 'Different RU module: '+name
            bundle = bundle[:start]+after.rstrip()+body[len(body.rstrip()):]+bundle[end:]
            optional[name] = after
            optional_meta[name] = {'before': sha(before), 'after': sha(after)}
        else:
            assert sha(before) == before_hashes[name], 'Different RU asset: '+name
            old[name], new[name] = before, after
    new['startup-shell.bundle.js'] = bundle
    build = sha(old['build-version.js']+b'\0master-order-300\0'+b''.join(
        n.encode()+new[n] for n in sorted(new)))[:20]
    new['index.html'] = old['index.html'].replace(BEFORE.encode(), build.encode())
    assert new['index.html'] != old['index.html']
    token = ("const BUILD_ID='"+BEFORE+"';").encode()
    assert old['sw.js'].count(token) == 1
    new['sw.js'] = old['sw.js'].replace(token, ("const BUILD_ID='"+build+"';").encode())
    updated = copy.deepcopy(meta)
    updated['id'], updated['shell'] = build, sha(new['index.html'])
    for name, data in new.items():
        if name in updated['assets']:
            updated['assets'][name] = sha(data)
    new['build-version.js'] = PREFIX+json.dumps(updated, ensure_ascii=False, separators=(',', ':')).encode()+b';\n'
    release = {'format': 1, 'main_sha': SOURCE, 'source_sha': SOURCE,
               'baseline_package_sha256': BASE_PACKAGE_SHA, 'before_build': BEFORE,
               'after_build': build, 'origin': prior['origin'], 'before': before_hashes,
               'after': {n: sha(b) for n, b in new.items()}, 'optional': optional_meta,
               'new_dirs': [], 'new_files': []}
    return release, old, new, optional

def build(previous):
    release, old, new, optional = prepare(previous)
    (HERE/'package/release.json').write_text(json.dumps(release, indent=2)+'\n')
    payload = {p.name: p.read_bytes() for p in (HERE/'package').iterdir() if p.is_file()}
    payload.update({'payload/'+n: b for n, b in new.items()})
    payload.update({'optional/'+n: b for n, b in optional.items()})
    with zipfile.ZipFile(HERE/'bos300.pyz', 'w', compression=zipfile.ZIP_DEFLATED) as z:
        for name, data in sorted(payload.items()):
            info = zipfile.ZipInfo(name, date_time=(2026, 10, 22, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, data)
    print('BEFORE_BUILD='+BEFORE)
    print('AFTER_BUILD='+release['after_build'])
    print('PACKAGE_SHA256='+sha((HERE/'bos300.pyz').read_bytes()))

if __name__ == '__main__':
    build(Path(sys.argv[1]).resolve())
