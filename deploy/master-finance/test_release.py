def bundle(reverse=False, code=b'const a=1;', source_map=b'{}', version='2.57.4'):
    uint = lambda n: struct.pack('>I', n)
    string = lambda s: uint(len(s.encode())) + s.encode()
    digest = lambda b: __import__('hashlib').sha256(b).digest()
    section = lambda b: uint(len(b)) + b + digest(b)
    modules = [('file:///bos-src/mini-app-api/supabase/functions/mini-app-api/index.ts', code, source_map),
               ('file:///bos-src/mini-app-api/order-payroll.js', b'const payroll=1;', b'')]
    if reverse: modules.reverse()
    header = sources = maps = b''
    for name, body, mapping in modules:
        header += string(name) + b'\0' + uint(len(sources)) + uint(len(body)) + uint(len(maps) if mapping else 0) + uint(len(mapping)) + b'\0'
        sources += body + digest(body)
        if mapping: maps += mapping + digest(mapping)
    header += string('@supabase/supabase-js@2') + b'\2' + uint(0)
    return b'ESZIP2.2' + section(bytes([0, 1])) + section(header) + section(string('@supabase/supabase-js@' + version) + uint(0)) + uint(len(sources)) + sources + uint(len(maps)) + maps


class FrozenTests(unittest.TestCase):
    def test_only_serialization_order_is_ignored(self):
        before = bundle()
        self.assertTrue(frozen.equal_baseline(before, bundle(reverse=True)))
        for changed in (bundle(code=b'const a=2;'), bundle(source_map=b'{"changed":true}'), bundle(version='2.58.0'), before + b'trailer'):
            self.assertFalse(frozen.equal_baseline(before, changed))

    def test_checksum_and_version_lock(self):
        with self.assertRaises(eszip.InvalidBundle): eszip.parse(bundle().replace(b'const a=1;', b'const a=2;'))
        graph = eszip.parse(bundle())
        lock = frozen.lockfile(graph, {'@supabase/supabase-js@2.57.4': 'sha512-test'})
        self.assertEqual(lock['specifiers'], {'npm:@supabase/supabase-js@2': '2.57.4'})
        self.assertEqual(set(lock['npm']), {'@supabase/supabase-js@2.57.4'})
        modules, _, logical = frozen.executable_modules(graph, backend.ENTRY)
        self.assertIn(logical, modules); self.assertEqual(len(modules), 2)


