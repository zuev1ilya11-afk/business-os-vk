        self.parent = Path(self.temp.name)
        self.root, self.stage = self.parent / 'release', self.parent / 'stage'
        for key, value in [('ROOT', self.root), ('PARENT', self.parent), ('STAGE', self.stage)]:
            p = patch.object(r, key, value); p.start(); self.addCleanup(p.stop)
        self.container = {key: {} for key in ('Config', 'HostConfig', 'Mounts')}
        self.container.update({'Id': 'fixture', 'Image': 'sha256:fixture'})
