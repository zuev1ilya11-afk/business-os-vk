import json
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.append(str(Path(__file__).resolve().parents[1] / 'finance-export'))
import build
import common
import web


class WebTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.payload = {'before/' + n: build.git_file(build.BASE, n) for n in [*build.FRONT, *build.MODELS]}
        cls.payload.update({'after/' + n: build.git_file(build.APP, n) for n in build.FRONT})

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(); self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        for name in (*web.EDITED, *web.MODELS):
            (self.root / name).write_bytes(self.payload['before/' + name])
        self.bundle = build.git_file(build.BASE, 'startup-shell.bundle.js') + b'\n// existing RU host change must stay\n'
        (self.root / 'startup-shell.bundle.js').write_bytes(self.bundle)
        (self.root / 'employee-profile-patch.js').write_text('// stale unused copy')
        self.before = '76372a6dd138d4168acd'
        (self.root / 'index.html').write_text('<html build="' + self.before + '"></html>')
        (self.root / 'sw.js').write_text("const BUILD_ID='" + self.before + "';\n// keep RU worker\n")
        meta = {'id': self.before, 'shell': common.sha((self.root / 'index.html').read_bytes()),
                'assets': {n: common.sha((self.root / n).read_bytes()) for n in (*web.EDITED[:-1], *web.MODELS, 'startup-shell.bundle.js')},
                'assetBundles': {'employee-profile-patch.js': 'startup-shell.bundle.js'}}
        (self.root / 'build-version.js').write_text('// Generated by npm run build. Do not edit.\nself.BOS_BUILD=' + json.dumps(meta) + ';\n')

    def test_overlay_changes_only_the_verified_module_inside_live_bundle(self):
        files, version = web.prepare(self.root, self.payload, self.before, build.APP)
        self.assertNotEqual(version, self.before)
        self.assertNotIn('web/employee-profile-patch.js', files)
        actual = files['web/startup-shell.bundle.js']
        old = self.payload['before/employee-profile-patch.js'].rstrip()
        new = self.payload['after/employee-profile-patch.js'].rstrip()
        self.assertEqual(actual.replace(new, old, 1), self.bundle)
        self.assertIn(b'// existing RU host change must stay', actual)
        for name, data in files.items(): (self.root / name.removeprefix('web/')).write_bytes(data)
        self.assertEqual(web.manifest(self.root)['id'], version)

    def test_changed_module_or_manifest_blocks_before_writing(self):
        before = common.tree(self.root)
        self.payload = dict(self.payload)
        self.payload['before/employee-profile-patch.js'] += b'\n// unverified baseline'
        with self.assertRaises(common.Stop): web.prepare(self.root, self.payload, self.before, build.APP)
        self.assertEqual(common.tree(self.root), before)

    def test_unverified_financial_model_blocks_overlay(self):
        payload = {**self.payload, 'before/order-payroll.js': b'other payroll rule'}
        with self.assertRaisesRegex(common.Stop, 'FINANCE_MODEL_CHANGED_order-payroll.js'):
            web.prepare(self.root, payload, self.before, build.APP)


if __name__ == '__main__': unittest.main()
