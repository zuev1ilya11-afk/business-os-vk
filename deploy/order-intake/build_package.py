"""Build the PR296 payload over verified RU assets, retaining all other fixes."""
import copy
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import zipfile

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
BASE = '3fb9bd0acc7cc954c53f52638127774e352e5a66'
MAIN = '27dccf2e61b64c44bfa96b97552425f04db97848'
SOURCE = '6b966c38fbd795612299dc2e793d10c452d7d6fe'
BEFORE = '77899953454eb1870e2e'
MANIFEST_SHA = '8218da5e8f6381938aef13331953b11507d43a7ecad683fb051126ff5f883a49'
NAMES = ['build-version.js', 'index.html', 'sw.js', 'startup-shell.bundle.js', 'startup-eager.bundle.js', 'order-control.js']
MODULES = [n for n in subprocess.check_output(['git','diff','--name-only',BASE,SOURCE],cwd=REPO).decode().splitlines() if '/' not in n and n.endswith('.js') and n not in ['build-version.js','sw.js','startup-shell.bundle.js','startup-eager.bundle.js']]
PREFIX = b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD='


def sha(data):
    return hashlib.sha256(data).hexdigest()


def source(revision, name):
    return subprocess.check_output(['git', 'show', revision + ':' + name], cwd=REPO)


def ru(data):
    return data.replace(b'https://obsropbslfwtanyspjbi.supabase.co', b'https://139.100.237.167').replace(
        b'https://business-os-api-gateway.netlify.app', b'https://139.100.237.167')


def replace_module(bundle, name, before, after):
    marker = b'// Source: ' + name.encode() + b'\n'
    assert bundle.count(marker) == 1, name
    start = bundle.index(marker) + len(marker)
    end = bundle.find(b'\n;\n// Source:', start)
    assert end > start and bundle[start:end].rstrip() == before.rstrip(), name
    tail = bundle[start:end][len(bundle[start:end].rstrip()):]
    return bundle[:start] + after.rstrip() + tail + bundle[end:]


def prepare(folder):
    with zipfile.ZipFile(folder) as previous:
        old = {name: previous.read('payload/'+name) for name in NAMES}
    assert sha(old['build-version.js']) == MANIFEST_SHA
    meta = json.loads(old['build-version.js'][len(PREFIX):-2])
    assert meta['id'] == BEFORE and sha(old['index.html']) == meta['shell']
    for name in ['startup-shell.bundle.js', 'startup-eager.bundle.js', 'order-control.js']:
        assert sha(old[name]) == meta['assets'][name], name
    new = {name: old[name] for name in ['startup-shell.bundle.js', 'startup-eager.bundle.js']}
    optional, optional_meta = {}, {}
    for name in MODULES:
        before, after = ru(source(BASE, name)), ru(source(SOURCE, name))
        bundle = meta.get('assetBundles', {}).get(name)
        if bundle:
            new[bundle] = replace_module(new[bundle], name, before, after)
            optional[name] = after
            optional_meta[name] = {'before': sha(before), 'after': sha(after)}
        else:
            assert sha(before) == meta['assets'][name], name
            old[name] = before
            new[name] = after
    build_id = sha(old['build-version.js'] + b'\0intake-296\0' + b''.join(name.encode()+new[name] for name in sorted(new)))[:20]
    new['index.html'] = old['index.html'].replace(BEFORE.encode(), build_id.encode())
    assert new['index.html'] != old['index.html']
    marker = ("const BUILD_ID='" + BEFORE + "';").encode()
    assert old['sw.js'].count(marker) == 1
    new['sw.js'] = old['sw.js'].replace(marker, ("const BUILD_ID='" + build_id + "';").encode())
    updated = copy.deepcopy(meta)
    updated['id'], updated['shell'] = build_id, sha(new['index.html'])
    for name, data in new.items():
        if name in updated['assets']:
            updated['assets'][name] = sha(data)
    new['build-version.js'] = PREFIX + json.dumps(updated, ensure_ascii=False, separators=(',', ':')).encode() + b';\n'
    release = {'format': 1, 'main_sha': MAIN, 'source_sha': SOURCE, 'before_build': BEFORE, 'after_build': build_id,
               'origin': 'https://139.100.237.167', 'before': {**meta['assets'], **{name: sha(data) for name, data in old.items()}},
               'after': {name: sha(data) for name, data in new.items()}, 'new_dirs': [], 'new_files': [], 'optional': optional_meta}
    for name in ['api-before.ts', 'api-after.ts', 'migration.sql']:
        release[name + '_sha256'] = sha((HERE / 'package' / name).read_bytes())
    return release, old, new, optional


def build(folder):
    release, old, new, optional = prepare(folder)
    (HERE / 'package/release.json').write_text(json.dumps(release, indent=2) + '\n')
    payload = {path.name: path.read_bytes() for path in (HERE / 'package').iterdir() if path.is_file()}
    payload.update({'payload/' + name: data for name, data in new.items()})
    payload.update({'optional/' + name: data for name, data in optional.items()})
    with zipfile.ZipFile(HERE / 'bos296.pyz', 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        for name, data in sorted(payload.items()):
            info = zipfile.ZipInfo(name, date_time=(2026,10,20,0,0,0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, data)
    print('AFTER_BUILD=' + release['after_build'])
    print('PACKAGE_SHA256=' + sha((HERE / 'bos296.pyz').read_bytes()))


if __name__ == '__main__':
    build(Path(sys.argv[1]).resolve())
