"""Pinned, frontend-only receipt-date overlay for the observed RU release."""
import argparse
import copy
import fcntl
import json
import os
from pathlib import Path
import subprocess
import sys
import core as c

SOURCE_REVISION = '73cbd60ac09792403011ef92246796d1eedc27d1'
BEFORE_BUILD = '2601cb81e246db1511dc'
ORIGIN = 'https://homemaster.qd.je'
PARENT = Path('/opt/business-os/deploy')
ROOT = PARENT / 'release-to2wblxf/web'
CONTAINER = 'bos-release-to2wblxf-https'
STAGE = PARENT / 'master-received-73cbd60'
SOURCES = ('approved-master-ui.css', 'master-daily-home-v127.js',
           'master-order-focus-v126.js', 'master-order-hands-layout-v72.js',
           'master-orders-v125.js')
BUNDLES = ('startup-shell.bundle.js', 'startup-eager.bundle.js')
VERSIONS = ('index.html', 'sw.js', 'build-version.js')
c.ALLOWED = set(SOURCES + BUNDLES + VERSIONS)
c.ORIGIN = ORIGIN


def require(condition, message):
    if not condition:
        raise c.Stop(message)


def patch_bytes(data, edits, label):
    # Each before-context must match exactly once. No fuzzy patching or wholesale
    # source replacement: server-only routing and unrelated fixes survive.
    for edit in edits:
        before, after = edit['before'].encode(), edit['after'].encode()
        require(before and data.count(before) == 1, 'PATCH_CONTEXT_DIFFERS: ' + label)
        data = data.replace(before, after, 1)
    return data


def patch_module(bundle, name, edits):
    marker = b'// Source: ' + name.encode() + b'\n'
    require(bundle.count(marker) == 1, 'BUNDLE_MODULE_DIFFERS: ' + name)
    start = bundle.index(marker) + len(marker)
    end = bundle.find(b'\n;\n// Source:', start)
    require(end >= 0, 'BUNDLE_BOUNDARY_DIFFERS: ' + name)
    return bundle[:start] + patch_bytes(bundle[start:end], edits, name) + bundle[end:]


def validate_manifest(root):
    meta = c.manifest(c.local_file(root, 'build-version.js').read_bytes())
    require(c.digest(c.local_file(root, 'index.html').read_bytes()) == meta['shell'],
            'CURRENT_SHELL_HASH_DIFFERS')
    for name, expected in meta['assets'].items():
        require(c.digest(c.local_file(root, name).read_bytes()) == expected,
                'CURRENT_ASSET_HASH_DIFFERS: ' + name)
    token = ("const BUILD_ID='" + meta['id'] + "';").encode()
    require(c.local_file(root, 'sw.js').read_bytes().count(token) == 1,
            'CURRENT_WORKER_BUILD_DIFFERS')
    return meta


def prepare(root, payload):
    require(payload['revision'] == SOURCE_REVISION and set(payload['edits']) == set(SOURCES),
            'PACKAGE_SCOPE_DIFFERS')
    meta = validate_manifest(root)
    require(meta['id'] == BEFORE_BUILD, 'BUILD_CHANGED: ' + meta['id'])
    old, new = {}, {}

    def read(name):
        if name not in old:
            old[name] = c.local_file(root, name).read_bytes()
        return old[name]

    for name in SOURCES:
        edits = payload['edits'][name]
        bundle = meta.get('assetBundles', {}).get(name)
        if bundle:
            require(bundle in BUNDLES and bundle in meta['assets'], 'UNKNOWN_BUNDLE: ' + name)
            data = new.get(bundle, read(bundle))
            new[bundle] = patch_module(data, name, edits)
            if (root / name).exists() or (root / name).is_symlink():
                new[name] = patch_bytes(read(name), edits, name)
        else:
            require(name in meta['assets'], 'SOURCE_NOT_IN_MANIFEST: ' + name)
            new[name] = patch_bytes(read(name), edits, name)

    build = c.digest((meta['id'] + SOURCE_REVISION + ''.join(
        name + c.digest(new[name]) for name in sorted(new))).encode())[:20]
    html = read('index.html')
    require(meta['id'].encode() in html, 'HTML_BUILD_MARKER_MISSING')
    new['index.html'] = html.replace(meta['id'].encode(), build.encode())
    worker = read('sw.js')
    new['sw.js'] = worker.replace(("const BUILD_ID='" + meta['id'] + "';").encode(),
                                 ("const BUILD_ID='" + build + "';").encode())
    read('build-version.js')
    updated = copy.deepcopy(meta)
    updated['id'], updated['shell'] = build, c.digest(new['index.html'])
    for name, data in new.items():
        if name in updated['assets']:
            updated['assets'][name] = c.digest(data)
    new['build-version.js'] = (b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD=' +
                              json.dumps(updated, ensure_ascii=False, separators=(',', ':')).encode() + b';\n')
    require(set(old) == set(new) and set(new) <= c.ALLOWED, 'INSTALL_SCOPE_DIFFERS')
    return old, new, build


def check_host():
    require(os.geteuid() == 0 and sys.platform == 'linux', 'RUN_ON_EXISTING_RU_HOST_AS_ROOT')
    require(PARENT.resolve() == PARENT and ROOT.resolve() == ROOT and ROOT.is_dir(),
            'OBSERVED_WEB_ROOT_MISSING')
    raw = subprocess.check_output(['docker', 'inspect', CONTAINER, '--format', '{{json .Mounts}}'],
                                  timeout=20, text=True)
    mounts = [m for m in json.loads(raw) if m.get('Destination') == '/srv']
    require(len(mounts) == 1 and mounts[0].get('Type') == 'bind'
            and mounts[0].get('Source') == str(ROOT) and mounts[0].get('RW') is False,
            'LIVE_FRONTEND_MOUNT_CHANGED')


def verify_public(files, build, fetch=c.get):
    for name, expected in files.items():
        require(fetch(ORIGIN + '/' + name + '?build=' + build) == expected,
                'PUBLIC_FILE_DIFFERS: ' + name)
    require(fetch(ORIGIN + '/') == files['index.html'], 'PUBLIC_ENTRY_POINT_DIFFERS')


def check_installed(record):
    files = {}
    for name, item in record['files'].items():
        require(name in c.ALLOWED, 'JOURNAL_SCOPE_DIFFERS')
        files[name] = c.local_file(ROOT, name).read_bytes()
        require(c.digest(files[name]) == item['after'], 'LATER_RELEASE_DETECTED: ' + name)
    meta = validate_manifest(ROOT)
    verify_public(files, meta['id'])
    return meta['id']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    for name in ('check', 'apply', 'rollback'):
        modes.add_argument('--' + name, action='store_true')
    args = parser.parse_args()
    check_host()
    os.umask(0o077)
    # Lock the existing directory itself, without creating a file during --check.
    lock = os.open(PARENT, os.O_RDONLY | os.O_DIRECTORY)
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        if STAGE.exists():
            require(not STAGE.is_symlink() and STAGE.resolve() == STAGE and STAGE.stat().st_uid == 0,
                    'UNSAFE_BACKUP_DIRECTORY')
            record = json.loads(c.local_file(STAGE, 'journal.json').read_text())
            require(record.get('revision') == SOURCE_REVISION and record.get('root') == str(ROOT),
                    'BACKUP_IDENTITY_DIFFERS')
            if args.rollback:
                c.rollback(ROOT, STAGE, record)
                validate_manifest(ROOT)
                previous = {n: c.local_file(STAGE, n).read_bytes() for n in record['files']}
                verify_public(previous, BEFORE_BUILD)
                print('RECEIVED_ROLLED_BACK BUILD_ID=' + BEFORE_BUILD)
                return
            if record['status'] == 'deployed':
                print('RECEIVED_ALREADY_DEPLOYED BUILD_ID=' + check_installed(record))
                return
            raise c.Stop('BACKUP_STATUS=' + record['status'] + '; retain it and inspect before retrying')
        require(not args.rollback, 'NO_BACKUP_FOR_THIS_RELEASE')
        import zipfile
        with zipfile.ZipFile(sys.argv[0]) as archive:
            payload = json.loads(archive.read('patches.json'))
        old, new, build = prepare(ROOT, payload)
        verify_public({n: old[n] for n in VERSIONS}, BEFORE_BUILD)
        print('RECEIVED_CHECK_OK BEFORE=' + BEFORE_BUILD + ' AFTER=' + build)
        print('FILES=' + ', '.join(new))
        if args.check:
            print('READ_ONLY=true')
            return

        def verify(files):
            validate_manifest(ROOT)
            verify_public(files, build)

        c.install(ROOT, STAGE, old, new, SOURCE_REVISION, verify)
        print('RECEIVED_DEPLOYED BUILD_ID=' + build)
        print('BACKUP=' + str(STAGE))
        print('No container restarts, database or backend changes.')
    finally:
        os.close(lock)


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        print('RECEIVED_STOPPED: ' + (str(error) if isinstance(error, c.Stop) else type(error).__name__))
        sys.exit(1)
