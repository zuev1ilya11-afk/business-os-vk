import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]


def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(spec)
    sys.modules[name] = result
    spec.loader.exec_module(result)
    return result


c = module('core', REPO / 'scripts/ru-master-home-release.py')
r = module('received_release', HERE / 'release.py')
b = module('received_builder', HERE / 'build.py')
PAYLOAD = b.payload()
BEFORE = {n: b.source(b.BASE, n).encode() for n in r.SOURCES}
AFTER = {n: b.source(b.REVISION, n).encode() for n in r.SOURCES}


class ReceiptReleaseTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name) / 'web'
        self.stage = Path(self.tmp.name) / 'backup'
        self.root.mkdir()
        self.files = {name: self.ru(data) for name, data in BEFORE.items()}
        # Model existing origin rewrites and an unrelated saved server-only fix.
        self.files['master-daily-home-v127.js'] += b'\n// SERVER_ONLY_FIX_RETAINED\n'
        self.files['config.js'] = b'window.PUBLIC_ORIGIN="https://homemaster.qd.je";\n'
        self.files['report-review-patch.js'] = b'// ACCEPT_REPORT_FIX_RETAINED\n'
        self.files['startup-shell.bundle.js'] = (
            b'// SERVER_ROUTING_RETAINED\n;\n// Source: master-order-hands-layout-v72.js\n' +
            self.files['master-order-hands-layout-v72.js'] +
            b'\n;\n// Source: report-review-patch.js\n' + self.files['report-review-patch.js'])
        self.files['index.html'] = ('<meta name="bos-build-id" content="' + r.BEFORE_BUILD +
                                    '"><script src="startup-shell.bundle.js?build=' + r.BEFORE_BUILD +
                                    '"></script><!-- SERVER_HTML_RETAINED -->').encode()
        self.files['sw.js'] = ("const BUILD_ID='" + r.BEFORE_BUILD + "';\n// SERVER_SW_RETAINED\n").encode()
        for name, data in self.files.items():
            (self.root / name).write_bytes(data)
        self.update_manifest()
        self.original = self.snapshot()

    @staticmethod
    def ru(data):
        return data.replace(b'https://obsropbslfwtanyspjbi.supabase.co', r.ORIGIN.encode())

    def snapshot(self):
        return {p.name: p.read_bytes() for p in self.root.iterdir()}

    def update_manifest(self, build=r.BEFORE_BUILD):
        meta = {'id': build, 'shell': c.digest((self.root / 'index.html').read_bytes()),
                'assets': {p.name: c.digest(p.read_bytes()) for p in self.root.iterdir()
                           if p.name not in (*r.VERSIONS, 'master-order-hands-layout-v72.js')},
                'assetBundles': {'master-order-hands-layout-v72.js': 'startup-shell.bundle.js'}}
        (self.root / 'build-version.js').write_bytes(
            b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD=' +
            json.dumps(meta, separators=(',', ':')).encode() + b';\n')

    def test_overlay_matches_reviewed_change_and_preserves_server_fixes(self):
        old, new, build = r.prepare(self.root, PAYLOAD)
        self.assertNotEqual(build, r.BEFORE_BUILD)
        for name in r.SOURCES:
            expected = self.ru(AFTER[name])
            if name == 'master-daily-home-v127.js':
                expected += b'\n// SERVER_ONLY_FIX_RETAINED\n'
            self.assertEqual(new[name], expected)
        self.assertIn(b'ACCEPT_REPORT_FIX_RETAINED', new['startup-shell.bundle.js'])
        self.assertIn(b'SERVER_ROUTING_RETAINED', new['startup-shell.bundle.js'])
        self.assertIn(b'SERVER_HTML_RETAINED', new['index.html'])
        self.assertIn(b'SERVER_SW_RETAINED', new['sw.js'])
        self.assertNotIn('config.js', new)
        self.assertEqual(self.snapshot(), self.original)
        meta = c.manifest(new['build-version.js'])
        self.assertEqual(meta['shell'], c.digest(new['index.html']))
        for name in new:
            if name in meta['assets']:
                self.assertEqual(meta['assets'][name], c.digest(new[name]))
        self.assertEqual(set(old), set(new))

    def test_ambiguous_or_changed_patch_context_is_rejected_without_writes(self):
        p = self.root / 'master-daily-home-v127.js'
        p.write_bytes(p.read_bytes().replace(b'masterV127CardTop', b'SERVER_DIFFERENT_HEADER'))
        self.update_manifest()
        before = self.snapshot()
        with self.assertRaisesRegex(c.Stop, 'PATCH_CONTEXT_DIFFERS'):
            r.prepare(self.root, PAYLOAD)
        self.assertEqual(self.snapshot(), before)
        with self.assertRaisesRegex(c.Stop, 'PATCH_CONTEXT_DIFFERS'):
            r.patch_bytes(b'old old', [{'before': 'old', 'after': 'new'}], 'ambiguous')

    def test_corrupt_unrelated_asset_blocks_the_release(self):
        (self.root / 'config.js').write_bytes(b'later runtime change')
        before = self.snapshot()
        with self.assertRaisesRegex(c.Stop, 'CURRENT_ASSET_HASH_DIFFERS: config.js'):
            r.prepare(self.root, PAYLOAD)
        self.assertEqual(self.snapshot(), before)
        self.assertFalse(self.stage.exists())

    def test_other_live_build_is_rejected_even_with_valid_asset_hashes(self):
        for name in ('index.html', 'sw.js'):
            p = self.root / name
            p.write_bytes(p.read_bytes().replace(r.BEFORE_BUILD.encode(), b'1' * 20))
        self.update_manifest(build='1' * 20)
        with self.assertRaisesRegex(c.Stop, 'BUILD_CHANGED'):
            r.prepare(self.root, PAYLOAD)

    def test_success_and_explicit_rollback_restore_exact_original_files(self):
        old, new, _ = r.prepare(self.root, PAYLOAD)
        record = c.install(self.root, self.stage, old, new, r.SOURCE_REVISION,
                           lambda _: r.validate_manifest(self.root))
        self.assertEqual(record['status'], 'deployed')
        self.assertEqual((self.root / 'config.js').read_bytes(), self.original['config.js'])
        for name, data in new.items():
            self.assertEqual((self.root / name).read_bytes(), data)
        c.rollback(self.root, self.stage, record)
        self.assertEqual(record['status'], 'rolled_back')
        self.assertEqual(self.snapshot(), self.original)

    def test_failed_https_verification_rolls_back_every_changed_file(self):
        old, new, _ = r.prepare(self.root, PAYLOAD)
        def fail(_):
            raise c.Stop('HTTPS mismatch')
        with self.assertRaisesRegex(c.Stop, 'HTTPS mismatch'):
            c.install(self.root, self.stage, old, new, r.SOURCE_REVISION, fail)
        self.assertEqual(self.snapshot(), self.original)
        self.assertEqual(json.loads((self.stage / 'journal.json').read_text())['status'], 'rolled_back')

    def test_interrupted_file_write_rolls_back(self):
        old, new, _ = r.prepare(self.root, PAYLOAD)
        atomic = c.atomic
        def fail(path, data, *args, **kwargs):
            if path == self.root / 'index.html' and data == new['index.html']:
                raise OSError('simulated disk error')
            return atomic(path, data, *args, **kwargs)
        with patch.object(c, 'atomic', side_effect=fail):
            with self.assertRaisesRegex(OSError, 'simulated'):
                c.install(self.root, self.stage, old, new, r.SOURCE_REVISION, lambda _: None)
        self.assertEqual(self.snapshot(), self.original)

    def test_rollback_never_overwrites_a_later_release(self):
        old, new, _ = r.prepare(self.root, PAYLOAD)
        record = c.install(self.root, self.stage, old, new, r.SOURCE_REVISION, lambda _: None)
        (self.root / 'index.html').write_bytes(b'later release')
        with self.assertRaisesRegex(c.Stop, 'outside this release'):
            c.rollback(self.root, self.stage, record)
        self.assertEqual((self.root / 'index.html').read_bytes(), b'later release')

    def test_symlinked_asset_is_rejected(self):
        p = self.root / 'config.js'
        target = Path(self.tmp.name) / 'outside.js'
        target.write_bytes(p.read_bytes())
        p.unlink()
        p.symlink_to(target)
        with self.assertRaisesRegex(c.Stop, 'symlinked'):
            r.prepare(self.root, PAYLOAD)

    def test_public_verification_checks_root_and_all_changed_files(self):
        _, new, build = r.prepare(self.root, PAYLOAD)
        calls = []
        def fetch(url):
            calls.append(url)
            return new['index.html'] if url == r.ORIGIN + '/' else new[url.split('/')[-1].split('?')[0]]
        r.verify_public(new, build, fetch)
        self.assertEqual(len(calls), len(new) + 1)
        with self.assertRaisesRegex(c.Stop, 'PUBLIC_ENTRY_POINT_DIFFERS'):
            r.verify_public(new, build, lambda url: b'stale root' if url == r.ORIGIN + '/' else fetch(url))

    def test_host_check_rejects_a_changed_mount(self):
        mounts = [{'Type': 'bind', 'Source': str(self.root), 'Destination': '/srv', 'RW': False}]
        with patch.object(r, 'ROOT', self.root), patch.object(r, 'PARENT', self.root.parent), \
             patch.object(r.os, 'geteuid', return_value=0), \
             patch.object(r.subprocess, 'check_output', return_value=json.dumps(mounts)):
            r.check_host()
        mounts[0]['Source'] = '/other/release/web'
        with patch.object(r, 'ROOT', self.root), patch.object(r, 'PARENT', self.root.parent), \
             patch.object(r.os, 'geteuid', return_value=0), \
             patch.object(r.subprocess, 'check_output', return_value=json.dumps(mounts)):
            with self.assertRaisesRegex(c.Stop, 'LIVE_FRONTEND_MOUNT_CHANGED'):
                r.check_host()

    def test_package_is_self_contained_and_check_does_not_write(self):
        package = HERE / 'bos-received.pyz'
        result = subprocess.run([sys.executable, str(package), '--help'], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        with patch.object(r, 'ROOT', self.root), patch.object(r, 'PARENT', self.root.parent), \
             patch.object(r, 'STAGE', self.stage), patch.object(r, 'check_host'), \
             patch.object(r, 'verify_public'), patch.object(sys, 'argv', [str(package), '--check']), \
             patch.object(c, 'install', side_effect=AssertionError('check must not install')):
            r.main()
        self.assertFalse(self.stage.exists())
        self.assertEqual(self.snapshot(), self.original)


if __name__ == '__main__':
    unittest.main()
