"""Package the CSS-only header fix over the observed RU frontend, never over Pages.

Input: directory with the four production-* files fetched through verified HTTPS.
Reuses the reviewed atomic frontend installer; no backend module is packaged.
"""
import copy
import hashlib
import json
from pathlib import Path
import sys
import zipfile

HERE=Path(__file__).resolve().parent
REPO=HERE.parent.parent
SOURCE='6592016d8c30f997bdc1724460a1405a845da46d'
BEFORE='4960149db306fca8149a'
NAMES=('approved-ui.css','index.html','sw.js','build-version.js')
PREFIX=b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD='

def sha(data):return hashlib.sha256(data).hexdigest()
def manifest(data):
    assert data.startswith(PREFIX) and data.endswith(b';\n')
    return json.loads(data[len(PREFIX):-2])

def build(source):
    old={n:(source/('production-'+n)).read_bytes() for n in NAMES}
    meta=manifest(old['build-version.js'])
    assert meta['id']==BEFORE and sha(old['index.html'])==meta['shell']
    assert sha(old['approved-ui.css'])==meta['assets']['approved-ui.css']
    # Refuse another stylesheet even when the supplied manifest describes it.
    import subprocess
    expected=subprocess.check_output(['git','show',SOURCE+'^:approved-ui.css'],cwd=REPO)
    reviewed=subprocess.check_output(['git','show',SOURCE+':approved-ui.css'],cwd=REPO)
    assert old['approved-ui.css']==expected
    assert (REPO/'approved-ui.css').read_bytes()==reviewed
    new={'approved-ui.css':reviewed}
    build_id=sha(old['build-version.js']+b'\0mobile-header\0'+reviewed)[:20]
    new['index.html']=old['index.html'].replace(BEFORE.encode(),build_id.encode())
    marker=("const BUILD_ID='"+BEFORE+"';").encode()
    assert old['sw.js'].count(marker)==1 and new['index.html']!=old['index.html']
    new['sw.js']=old['sw.js'].replace(marker,("const BUILD_ID='"+build_id+"';").encode())
    updated=copy.deepcopy(meta)
    updated['id']=build_id
    updated['shell']=sha(new['index.html'])
    updated['assets']['approved-ui.css']=sha(reviewed)
    new['build-version.js']=PREFIX+json.dumps(updated,ensure_ascii=False,separators=(',',':')).encode()+b';\n'
    before=dict(meta['assets'])
    before.update({n:sha(data) for n,data in old.items()})
    release=dict(format=1,main_sha=SOURCE,source_sha=SOURCE,
                 before_build=BEFORE,after_build=build_id,origin='https://139.100.237.167',
                 before=before,after={n:sha(data) for n,data in new.items()},
                 new_dirs=[],new_files=[],optional={})
    helper=(REPO/'deploy/pr289/package/frontend.py').read_text()
    helper=helper.replace("MAIN = '99ae7b989d6adbce10d00fe4ebebfc2ad136150c'",f"MAIN = '{SOURCE}'")
    helper=helper.replace("STAGE = PARENT / 'pr289-web'","STAGE = PARENT / 'mobile-header-294'")
    helper=helper.replace('PR #289','mobile header fix').replace('bos289.pyz','bosheader.pyz')
    # Execute the helper as __main__ so its normal signal/error handling remains.
    entry="import runpy\nrunpy.run_module('frontend', run_name='__main__')\n"
    payload={'__main__.py':entry.encode(),'frontend.py':helper.encode(),
             'release.json':(json.dumps(release,indent=2)+'\n').encode()}
    payload.update({'payload/'+n:data for n,data in new.items()})
    payload.update({'baseline/'+n:data for n,data in old.items()})
    with zipfile.ZipFile(HERE/'bosheader.pyz','w',compression=zipfile.ZIP_DEFLATED) as archive:
        for name,data in sorted(payload.items()):
            info=zipfile.ZipInfo(name,date_time=(2026,10,15,0,0,0))
            info.compress_type=zipfile.ZIP_DEFLATED
            archive.writestr(info,data)
    (HERE/'release-manifest.json').write_text(json.dumps(release,indent=2)+'\n')
    print('RU_BUILD='+build_id)
    print('PACKAGE_SHA256='+sha((HERE/'bosheader.pyz').read_bytes()))

if __name__=='__main__':build(Path(sys.argv[1]).resolve())
