"""Only the reviewed price modules; preserve deployed endpoint mappings."""
import copy
import importlib.util
import json
from pathlib import Path
import re
from common import read, require, sha

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('report_source_overlay', ROOT/'deploy/report-submit/overlay.py')
previous = importlib.util.module_from_spec(spec)
spec.loader.exec_module(previous)
APIS = (*previous.APIS, 'mini-app-api')
def dependencies(name):
    return ('supabase/functions/_shared/finance-export-models.mjs',) if name == 'mini-app-api' else ('service-catalog.js', 'report-deduction.js')
BASELINES = json.loads(read(Path(__file__).parent/'baselines.json'))
LEGACY_FINANCE = json.loads(read(Path(__file__).parent/'legacy-finance.json'))['files']
WEB = tuple(n for n in BASELINES if '/' not in n)


def web_target(meta, name):
    routes = meta.get('assetBundles', {})
    if name in routes:
        target = routes[name]
        require(target in ('startup-shell.bundle.js', 'startup-eager.bundle.js'), 'PRICE_MODULE_BUNDLE_'+name)
    else:
        target = name
    require(target in meta['assets'], 'PRICE_MODULE_NOT_IN_MANIFEST_'+name)
    return target


def api_ready(name, current):
    if name in previous.APIS:
        require(sha(current) == previous.AFTER[name], 'REPORT_FIX_REQUIRED_OR_API_CHANGED_'+name)


def module(name, current, repo):
    pair = BASELINES[name]
    after = read(repo/name)
    require(after == pair['after'].encode(), 'PRICE_CHECKOUT_CHANGED_'+name)
    if name in LEGACY_FINANCE:
        legacy = LEGACY_FINANCE[name]
        pattern = re.compile(b'|'.join(re.escape(x.encode()) for x in previous.ORIGINS))
        normalize = lambda value: pattern.sub(b'@ORIGIN@', value).rstrip()
        if normalize(current) == normalize(legacy['before'].encode()):
            return previous.preserve_origins(legacy['before'].encode(),current,legacy['after'].encode(),'price-legacy:'+name)
    if name == 'employee-profile-patch.js':
        # Only the self-contained price-tab presentation belongs to this release.
        # Production has a different employee-finance implementation; retain it
        # byte for byte, and reject any drift inside the price-tab section itself.
        before = pair['before'].encode()
        begin = b"  const catalog=modal.querySelector('.bosSharedCatalog'),"
        end = b"\n  const toolsHead=modal.querySelector('.ownerToolsHead');"
        def bounds(data):
            require(data.count(begin) == data.count(end) == 1, 'PROFILE_PRICE_SECTION_COUNT')
            first, last = data.index(begin), data.index(end)
            require(first < last, 'PROFILE_PRICE_SECTION_ORDER')
            return first, last
        a, b = bounds(before)
        c, d = bounds(after)
        require(before[:a] == after[:c] and before[b:] == after[d:], 'PROFILE_PATCH_SCOPE')
        i, j = bounds(current)
        require(current[i:j] == before[a:b], 'PROFILE_PRICE_SECTION_CHANGED')
        return current[:i] + after[c:d] + current[j:]
    return previous.preserve_origins(pair['before'].encode(), current, after, 'price:'+name)


def frontend(web, repo):
    raw = read(web/'build-version.js')
    match = re.fullmatch(rb'// Generated by npm run build\. Do not edit\.\nself\.BOS_BUILD=(\{.*\});\n',raw,re.S)
    require(match is not None,'MANIFEST_FORMAT')
    meta = json.loads(match[1])
    require(re.fullmatch('[a-f0-9]{20}',meta['id']),'BUILD_FORMAT')
    require(sha(read(web/'index.html')) == meta['shell'],'SHELL_HASH_CHANGED')
    for name,digest in meta['assets'].items():
        require(re.fullmatch('[A-Za-z0-9_.-]+',name) and name not in ('.','..'),'ASSET_PATH')
        require(sha(read(web/name)) == digest,'ASSET_HASH_CHANGED_'+name)
    edited = {}
    for name in WEB:
        bundle = web_target(meta, name)
        if bundle == name:
            edited['web/'+name] = module(name, read(web/name), repo)
            continue
        data = edited.get('web/'+bundle,read(web/bundle))
        marker = b'// Source: '+name.encode()+b'\n'
        require(data.count(marker) == 1,'PRICE_MODULE_COUNT_'+name)
        start = data.index(marker)+len(marker)
        end = data.find(b'\n;\n// Source:',start)
        require(end > start,'PRICE_MODULE_BOUNDARY_'+name)
        original = data[start:end]
        changed = module(name,original,repo).rstrip()+original[len(original.rstrip()):]
        data = data[:start]+changed+data[end:]
        edited['web/'+bundle] = data
        if (web/name).exists():
            edited['web/'+name] = module(name,read(web/name),repo)
    build = sha((meta['id']+''.join(n+sha(edited[n]) for n in sorted(edited))).encode())[:20]
    html = read(web/'index.html')
    require(meta['id'].encode() in html,'HTML_VERSION_MISSING')
    edited['web/index.html'] = html.replace(meta['id'].encode(),build.encode())
    worker = read(web/'sw.js')
    old = ("const BUILD_ID='"+meta['id']+"';").encode()
    require(worker.count(old) == 1,'WORKER_VERSION_MISSING')
    edited['web/sw.js'] = worker.replace(old,("const BUILD_ID='"+build+"';").encode())
    new = copy.deepcopy(meta)
    new['id'],new['shell'] = build,sha(edited['web/index.html'])
    for name,value in edited.items():
        key = name.removeprefix('web/')
        if key in new['assets']:
            new['assets'][key] = sha(value)
    edited['web/build-version.js'] = b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD='+json.dumps(new,ensure_ascii=False,separators=(',',':')).encode()+b';\n'
    return edited,build,meta['id']
