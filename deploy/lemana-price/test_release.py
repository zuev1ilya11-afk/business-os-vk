class PriceOverlayTests(unittest.TestCase):
    def fixture(self, root):
        root.mkdir()
        version = 'a'*20
        rewrite = lambda b:b.replace(b'https://business-os-api-gateway.netlify.app',b'https://139.100.237.167').replace(b'https://obsropbslfwtanyspjbi.supabase.co',b'https://139.100.237.167')
        files = {n:rewrite(v['before'].encode()) for n,v in overlay.BASELINES.items() if n in overlay.WEB}
        files['startup-shell.bundle.js'] = b'// original bundle\n'+b''.join(b'\n;\n// Source: '+n.encode()+b'\n'+v+b'\n' for n,v in files.items() if n!='finance-data.js')+b'\n;\n// Source: unaffected.js\nconst retained=42;\n'
        files['startup-eager.bundle.js'] = b'// Source: finance-data.js\n'+files['finance-data.js']+b'\n;\n// Source: unaffected.js\nconst retained=42;\n'
        files['index.html'] = ('<script src="startup-shell.bundle.js?v='+version+'"></script>').encode()
        files['sw.js'] = ("const BUILD_ID='"+version+"';").encode()
        for n,v in files.items():
            (root/n).write_bytes(v)
        meta = dict(id=version,shell=r.sha(files['index.html']),assets={n:r.sha(v) for n,v in files.items() if n!='index.html'},assetBundles={n:('startup-eager.bundle.js' if n=='finance-data.js' else 'startup-shell.bundle.js') for n in overlay.WEB})
        (root/'build-version.js').write_bytes(b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD='+json.dumps(meta,separators=(',',':')).encode()+b';\n')
        return files,rewrite

    def test_every_module_updated_without_rewriting_live_files_or_origins(self):
        with tempfile.TemporaryDirectory() as tmp:
            root=Path(tmp)/'web';old,rewrite=self.fixture(root)
            new,build,before=overlay.frontend(root,r.REPO)
            self.assertNotEqual(build,before)
            for n,pair in overlay.BASELINES.items():
                if n not in overlay.WEB:continue
                self.assertEqual(new['web/'+n],rewrite(pair['after'].encode()))
                self.assertEqual((root/n).read_bytes(),old[n])
            self.assertIn(b'const retained=42;',new['web/startup-shell.bundle.js'])
            meta=json.loads(new['web/build-version.js'].split(b'self.BOS_BUILD=')[1][:-2])
            self.assertEqual(meta['shell'],r.sha(new['web/index.html']))
            for n,digest in meta['assets'].items():
                self.assertEqual(digest,r.sha(new.get('web/'+n,old[n])))

    def test_unknown_live_changes_and_unfixed_report_api_are_blocked(self):
        for n,pair in overlay.BASELINES.items():
            if n=='employee-profile-patch.js':continue
            with contextlib.redirect_stdout(io.StringIO()),self.assertRaises(r.Stop):
                overlay.module(n,pair['before'].encode()+b'\nconst unknown=1;',r.REPO)
        for name in overlay.previous.APIS:
            with self.assertRaises(r.Stop):
                overlay.api_ready(name,b'unknown')

    def test_profile_price_patch_preserves_deployed_finance_and_rejects_tab_drift(self):
        name='employee-profile-patch.js'
        pair=overlay.BASELINES[name]
        before,after=(pair[k].encode() for k in ('before','after'))
        change=lambda data:data.replace(b'const financial=',b'const retainedFinancial=')+b'\n// deployed-only profile change\n'
        current=change(before)
        self.assertEqual(overlay.module(name,current,r.REPO),change(after))
        for invalid in (
            current.replace(b'const sections={catalog,avito,materials};',b'const sections={catalog,avito};'),
            current+current,
            after,
        ):
            with self.assertRaises(r.Stop):
                overlay.module(name,invalid,r.REPO)

    def test_actual_manifest_layout_updates_standalone_finance(self):
        with tempfile.TemporaryDirectory() as tmp:
            root=Path(tmp)/'web';old,rewrite=self.fixture(root)
            actual=json.loads((r.REPO/'build-version.js').read_bytes().split(b'self.BOS_BUILD=')[1][:-2])
            self.assertNotIn('finance-data.js',actual['assetBundles'])
            path=root/'build-version.js'
            meta=json.loads(path.read_bytes().split(b'self.BOS_BUILD=')[1][:-2])
            meta['assetBundles']={n:actual['assetBundles'][n] for n in overlay.WEB if n in actual['assetBundles']}
            # The eager bundle no longer carries the finance module in this layout.
            eager=b'// Source: unaffected.js\nconst retained=42;\n'
            (root/'startup-eager.bundle.js').write_bytes(eager)
            meta['assets']['startup-eager.bundle.js']=r.sha(eager)
            path.write_bytes(b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD='+json.dumps(meta).encode()+b';\n')
            new,_,_=overlay.frontend(root,r.REPO)
            self.assertNotIn('web/startup-eager.bundle.js',new)
            self.assertEqual(new['web/finance-data.js'],rewrite(overlay.BASELINES['finance-data.js']['after'].encode()))
            final=json.loads(new['web/build-version.js'].split(b'self.BOS_BUILD=')[1][:-2])
            self.assertEqual(final['assets']['finance-data.js'],r.sha(new['web/finance-data.js']))
            del meta['assets']['finance-data.js']
            with self.assertRaises(r.Stop):overlay.web_target(meta,'finance-data.js')


class InstallTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name)
        self.live=self.root/'live'
        self.work=self.root/'work'
        self.stage=self.work/'stage-test'
        self.stage.mkdir(parents=True)
        (self.stage/'logs').mkdir()
        targets=r.module_paths()|{'edge/bundles/'+n+'.eszip' for n in overlay.APIS}
        targets|={'web/'+n for n in ('startup-shell.bundle.js','startup-eager.bundle.js','index.html','sw.js','build-version.js')}
        self.record=dict(status='verified',edge='fingerprint',before={'snapshot':1},build='b'*20,
                         old_build='a'*20,tests={'isolated':True},files={})
        for path in sorted(targets):
            old=('old:'+path).encode()
            new=('new:'+path).encode()
            if path=='web/build-version.js':
                meta={'assets':{'startup-eager.bundle.js':'test','startup-shell.bundle.js':'test'},'assetBundles':{n:('startup-eager.bundle.js' if n=='finance-data.js' else 'startup-shell.bundle.js') for n in overlay.WEB}}
                old=b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD='+json.dumps(meta).encode()+b';\n'
            for folder,data in [(self.live,old),(self.stage/'backup',old),(self.stage/'candidate',new)]:
                target=folder/path
                target.parent.mkdir(parents=True,exist_ok=True)
                target.write_bytes(data)
            self.record['files'][path]={'before':r.item(self.live/path),'after':r.sha(new)}
        r.save_record(self.stage,self.record)
        (self.work/'current.json').write_text(json.dumps({'stage':'stage-test'}))
        self.patches=[patch.object(r,'LIVE',self.live),patch.object(r,'WORK',self.work),
            patch.object(r,'host',return_value={}),patch.object(r,'fingerprint',return_value='fingerprint'),
            patch.object(r,'snapshot',return_value={'snapshot':1}),patch.object(r,'emit')]
        for p in self.patches:
            p.start()
            self.addCleanup(p.stop)

    def public_check(self,work,record,which):
        for path,info in record['files'].items():
            if path.startswith('web/'):
                self.assertEqual(r.sha((self.live/path).read_bytes()),
                    info['before']['sha'] if which=='before' else info['after'])

    def assert_state(self,which):
        for path,info in self.record['files'].items():
            expected=info['before']['sha'] if which=='before' else info['after']
            self.assertEqual(r.item(self.live/path)['sha'],expected)

    def test_install_and_explicit_rollback(self):
        with patch.object(r,'run') as run,patch.object(r,'health'),patch.object(r,'public_matches',side_effect=self.public_check):
            r.apply()
            self.assert_state('after')
            self.assertEqual(json.loads((self.stage/'journal.json').read_text())['status'],'applied')
            r.apply()  # idempotent: no second restart
            self.assertEqual(run.call_count,1)
            r.apply(rollback=True)
            self.assert_state('before')
            self.assertEqual(run.call_count,2)

    def test_shell_only_layout_does_not_require_untouched_eager_bundle(self):
        path='web/build-version.js'
        meta={'assets':{'startup-shell.bundle.js':'test'},'assetBundles':{n:'startup-shell.bundle.js' for n in overlay.WEB}}
        old=b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD='+json.dumps(meta).encode()+b';\n'
        (self.live/path).write_bytes(old)
        (self.stage/'backup'/path).write_bytes(old)
        self.record['files'][path]['before']=r.item(self.live/path)
        del self.record['files']['web/startup-eager.bundle.js']
        r.save_record(self.stage,self.record)
        with patch.object(r,'run'),patch.object(r,'health'),patch.object(r,'public_matches',side_effect=self.public_check):
            r.apply()
            self.assert_state('after')

    def test_standalone_finance_is_required_and_installs_with_shell(self):
        path='web/build-version.js'
        meta={'assets':{'startup-shell.bundle.js':'test','finance-data.js':'test'},'assetBundles':{n:'startup-shell.bundle.js' for n in overlay.WEB if n!='finance-data.js'}}
        old=b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD='+json.dumps(meta).encode()+b';\n'
        (self.live/path).write_bytes(old)
        (self.stage/'backup'/path).write_bytes(old)
        self.record['files'][path]['before']=r.item(self.live/path)
        del self.record['files']['web/startup-eager.bundle.js']
        r.save_record(self.stage,self.record)
        with self.assertRaises(r.Stop):r.selected()
        path='web/finance-data.js'
        for folder,data in [(self.live,b'old finance'),(self.stage/'backup',b'old finance'),(self.stage/'candidate',b'new finance')]:
            (folder/path).write_bytes(data)
        self.record['files'][path]={'before':r.item(self.live/path),'after':r.sha(b'new finance')}
        r.save_record(self.stage,self.record)
        with patch.object(r,'run'),patch.object(r,'health'),patch.object(r,'public_matches',side_effect=self.public_check):
            r.apply()
            self.assert_state('after')
            r.apply(rollback=True)
            self.assert_state('before')

    def test_failed_health_restores_before_files(self):
        with patch.object(r,'run'),patch.object(r,'health',side_effect=[r.Stop('HEALTH_FAILED'),None]), \
             patch.object(r,'public_matches',side_effect=self.public_check):
            with self.assertRaises(r.Stop):
                r.apply()
        self.assert_state('before')
        self.assertEqual(json.loads((self.stage/'journal.json').read_text())['status'],'rolled_back')

    def test_failed_public_check_restores_api_and_web(self):
        def public(work,record,which):
            if which=='after':
                raise r.Stop('PUBLIC_ASSET_DIFFERS')
            self.public_check(work,record,which)
        with patch.object(r,'run'),patch.object(r,'health'),patch.object(r,'public_matches',side_effect=public):
            with self.assertRaises(r.Stop):
                r.apply()
        self.assert_state('before')

    def test_changed_production_or_candidate_stops_before_restart(self):
        with patch.object(r,'snapshot',return_value={'changed':1}),patch.object(r,'run') as run:
            with self.assertRaises(r.Stop):
                r.apply()
            run.assert_not_called()
        path=next(iter(self.record['files']))
        (self.stage/'candidate'/path).write_bytes(b'tampered')
        with patch.object(r,'run') as run:
            with self.assertRaises(r.Stop):
                r.apply()
            run.assert_not_called()
        self.assert_state('before')

    def test_unknown_file_cannot_be_rolled_back_over(self):
        with patch.object(r,'run'),patch.object(r,'health'),patch.object(r,'public_matches'):
            r.apply()
        path=next(iter(self.record['files']))
        (self.live/path).write_bytes(b'another-release')
        with patch.object(r,'run') as run:
            with self.assertRaises(r.Stop):
                r.apply(rollback=True)
            run.assert_not_called()
        self.assertEqual((self.live/path).read_bytes(),b'another-release')


