"""Read-only diagnostic contract; synthetic containers and files only."""
import contextlib
import importlib.util
import io
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

spec = importlib.util.spec_from_file_location('check297', Path(__file__).with_name('check.py'))
c = importlib.util.module_from_spec(spec)
spec.loader.exec_module(c)


class CheckTests(unittest.TestCase):
    def test_database_is_resolved_from_rest_not_first_running_postgres(self):
        rest = {'Config': {'Env': ['PGRST_DB_URI=postgres://role:private-password@active-db:5432/postgres']},
                'NetworkSettings': {'Networks': {'release': {}}}}
        old = {'Name': '/old-db', 'NetworkSettings': {'Networks': {'other': {'Aliases': ['active-db']}}}}
        active = {'Name': '/release-db', 'NetworkSettings': {'Networks': {'release': {'Aliases': ['active-db']}}}}
        self.assertEqual(c.find_db(rest, [old, active]), (active, 'postgres'))
        with self.assertRaises(c.Stop):
            c.find_db(rest, [active, active])

    def test_sql_requires_select_inside_read_only_transaction(self):
        calls = []
        with patch.object(c, 'run', side_effect=lambda args: calls.append(args) or '{}'):
            c.sql({'Id': 'synthetic-db'}, 'postgres', "SELECT json_build_object('version',1)")
            with self.assertRaises(c.Stop):
                c.sql({'Id': 'synthetic-db'}, 'postgres', 'UPDATE orders SET amount=0')
        self.assertEqual(len(calls), 1)
        self.assertTrue(calls[0][-1].startswith('BEGIN READ ONLY;'))

    def test_full_diagnostic_prints_metadata_only_and_never_mutates(self):
        with tempfile.TemporaryDirectory() as folder:
            base = Path(folder)
            release = base / 'release-test'
            sources = release / 'edge/sources'
            bundles = release / 'edge/bundles'
            web = release / 'web'
            for p in [sources, bundles, web]:
                p.mkdir(parents=True)
            code = b'// synthetic private-code-secret\n'
            entry = sources / 'mini-app-api/supabase/functions/mini-app-api/index.ts'
            entry.parent.mkdir(parents=True)
            entry.write_bytes(code)
            (sources / 'mini-app-api/order-payroll.js').write_bytes(code)
            (bundles / 'mini-app-api.eszip').write_bytes(b'synthetic-bundle')
            (web / 'index.html').write_bytes(b'<html>synthetic</html>')
            manifest = {'id': 'synthetic-build', 'assets': {}, 'shell': c.sha((web / 'index.html').read_bytes())}
            (web / 'build-version.js').write_text('// Generated by npm run build. Do not edit.\nself.BOS_BUILD=' + json.dumps(manifest) + ';\n')
            edge = {'Id': 'edge', 'Name': '/bos-release-test-edge', 'Mounts': [
                {'Type': 'bind', 'Source': str(sources), 'Destination': '/bos-src'},
                {'Type': 'bind', 'Source': str(bundles), 'Destination': '/bos-bundles'}]}
            https = {'Id': 'https', 'Name': '/bos-release-test-https', 'Mounts': [
                {'Type': 'bind', 'Source': str(web), 'Destination': '/srv'}]}
            rest = {'Id': 'rest', 'Name': '/bos-release-test-rest', 'Config': {'Env': [
                'PGRST_DB_URI=postgres://role:private-password@db:5432/postgres']},
                'NetworkSettings': {'Networks': {'release': {}}}}
            db = {'Id': 'db', 'Name': '/bos-release-test-db', 'NetworkSettings': {
                'Networks': {'release': {'Aliases': ['db']}}}}
            commands = []
            def run(args, **kwargs):
                commands.append(args)
                if args == ['docker', 'ps', '-q']: return 'edge https rest db'
                if args[:2] == ['docker', 'inspect']: return json.dumps([edge, https, rest, db])
                if args[:5] == ['docker', 'exec', '-u', 'postgres', 'db']:
                    self.assertEqual(args[5], 'psql')
                    self.assertTrue(args[-1].startswith('BEGIN READ ONLY;'))
                    self.assertIn('information_schema.columns', args[-1])
                    self.assertNotIn('FROM public.orders', args[-1])
                    return '{"version":"17.11"}'
                self.fail('Unexpected command: ' + str(args))
            before = {str(p): p.read_bytes() for p in base.rglob('*') if p.is_file()}
            stdout = io.StringIO()
            with patch.object(c, 'BASE', base), patch.object(c, 'run', run), contextlib.redirect_stdout(stdout):
                c.main()
            self.assertEqual(before, {str(p): p.read_bytes() for p in base.rglob('*') if p.is_file()})
            output = stdout.getvalue()
            self.assertIn('CHECK_ONLY=', output)
            self.assertIn('"integrity":true', output)
            self.assertNotIn('private-password', output)
            self.assertNotIn('private-code-secret', output)
            self.assertEqual(len(commands), 3)


if __name__ == '__main__':
    unittest.main()
