#!/usr/bin/env python3
"""Read-only RU Lemana release check. No writes, restarts or customer data.

Reads public code, Docker routing metadata and schema metadata. Never prints
Docker environment, connection strings, passwords, tokens or database rows.
"""
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
from urllib.parse import unquote, urlsplit
BASE=Path('/opt/business-os/deploy')
BASE_BODY='0a94d912cf393b9dd896aff88915809890ec8c42f395e81e2eda3b170beb1492'
TARGET_BODY='not-installed'
class Stop(Exception):
    """Fixed diagnostic messages only; no subprocess stderr or configuration."""


def emit(key, value):
    print(key + '=' + json.dumps(value, ensure_ascii=True, separators=(',', ':')), flush=True)


def run(args, timeout=20):
    try:
        result = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired):
        raise Stop('COMMAND_UNAVAILABLE_OR_TIMEOUT') from None
    if result.returncode:
        raise Stop('COMMAND_FAILED_EXIT_' + str(result.returncode))
    return result.stdout


def sha(data):
    return hashlib.sha256(data).hexdigest()


def cname(container):
    return container['Name'].lstrip('/')


def find_db(rest, containers):
    values = dict(x.split('=', 1) for x in rest['Config'].get('Env', []) if '=' in x)
    try:
        uri = urlsplit(values.get('PGRST_DB_URI', ''))
        dbname = unquote(uri.path.lstrip('/'))
        if uri.scheme not in ('postgres', 'postgresql') or not uri.hostname or not re.fullmatch(r'[A-Za-z0-9_]+', dbname):
            raise ValueError()
        host = uri.hostname
    except ValueError:
        raise Stop('REST_DATABASE_FORMAT_UNKNOWN') from None
    found = []
    for item in containers:
        if not cname(item).endswith('-db'):
            continue
        networks = item['NetworkSettings']['Networks']
        for network in set(rest['NetworkSettings']['Networks']) & set(networks):
            info = networks[network]
            aliases = (info.get('Aliases') or []) + (info.get('DNSNames') or [])
            if host in [cname(item), info.get('IPAddress'), *aliases]:
                found.append(item)
                break
    if len(found) != 1:
        raise Stop('REST_DATABASE_TARGET_MISSING_OR_AMBIGUOUS')
    return found[0], dbname


def sql(db, dbname, query):
    if not query.lstrip().upper().startswith('SELECT '):
        raise Stop('SELECT_REQUIRED')
    statement = "BEGIN READ ONLY; SET LOCAL statement_timeout='5s'; SET LOCAL lock_timeout='2s'; " + query + '; COMMIT;'
    raw = run(['docker', 'exec', '-u', 'postgres', db['Id'], 'psql', '-X', '-qAt',
               '-U', 'postgres', '-d', dbname, '-v', 'ON_ERROR_STOP=1', '-c', statement])
    return json.loads(raw.strip())


def mount_root(container, destination):
    matches = [m for m in container.get('Mounts', []) if m.get('Type') == 'bind' and m.get('Destination') == destination]
    if len(matches) != 1:
        raise Stop('EXPECTED_BIND_MISSING')
    root = Path(matches[0]['Source'])
    if root.resolve() != root or not root.is_relative_to(BASE) or not root.is_dir():
        raise Stop('UNREVIEWED_RELEASE_PATH')
    if any(m.get('Destination', '').startswith(destination + '/') for m in container.get('Mounts', [])):
        raise Stop('NESTED_MOUNT_NOT_SUPPORTED')
    return root


def read(root, relative, limit=8_000_000):
    path = root / relative
    if (not re.fullmatch(r'[A-Za-z0-9_./-]+', relative) or Path(relative).is_absolute()
            or '..' in Path(relative).parts or not path.is_relative_to(root)):
        raise Stop('UNSAFE_RELEASE_PATH')
    if path.resolve() != path:
        raise Stop('SYMLINKED_RELEASE_FILE:' + relative)
    if not path.is_file():
        raise Stop('MISSING_RELEASE_FILE:' + relative)
    if path.stat().st_size > limit:
        raise Stop('OVERSIZED_RELEASE_FILE:' + relative)
    return path.read_bytes()


def main():
    ids=run(['docker','ps','-q']).split()
    if not ids: raise Stop('NO_RUNNING_CONTAINERS')
    containers=json.loads(run(['docker','inspect',*ids]))
    edges=[c for c in containers if cname(c).startswith('bos-release-') and cname(c).endswith('-edge')]
    if len(edges)!=1: raise Stop('EDGE_MISSING_OR_AMBIGUOUS')
    edge=edges[0];sources=mount_root(edge,'/bos-src');bundles=mount_root(edge,'/bos-bundles')
    web=sources.parent.parent/'web'
    caddies=[c for c in containers if any(m.get('Type')=='bind' and m.get('Destination')=='/srv' and Path(m.get('Source',''))==web for m in c.get('Mounts',[]))]
    if len(caddies)!=1 or mount_root(caddies[0],'/srv')!=web: raise Stop('WEB_EDGE_RELEASE_DISAGREE')
    raw=read(web,'build-version.js');match=re.fullmatch(rb'// Generated by npm run build\. Do not edit\.\nself\.BOS_BUILD=(\{.*\});\n',raw,re.S)
    if not match: raise Stop('UNKNOWN_WEB_MANIFEST')
    meta=json.loads(match[1]);failures=[]
    for name,digest in {**meta['assets'],'index.html':meta['shell']}.items():
        if sha(read(web,name))!=digest: failures.append(name)
    emit('WEB',dict(build=meta['id'],manifest_sha256=sha(raw),integrity=not failures,mismatched=failures))
    entry='mini-app-api/supabase/functions/mini-app-api/index.ts'
    code=read(sources,entry).decode();normalized=sha(re.sub(r'^import [^\n]+;\n','',code,flags=re.M).encode())
    emit('API',dict(name='mini-app-api',source_sha256=sha(code.encode()),body_sha256=normalized,baseline=normalized==BASE_BODY,target=normalized==TARGET_BODY,bundle_sha256=sha(read(bundles,'mini-app-api.eszip',32000000))))
    imports=re.findall(r'^import [^\n]+;',code,re.M)
    # Relative imports are code paths, not environment values; report hashes only.
    deps=[]
    for line in imports:
        match=re.search(r'[\'"]([.][^\'"]+)[\"]',line)
        if not match: continue
        dep=(sources/entry).parent.joinpath(match[1]).resolve()
        if not dep.is_relative_to(sources): raise Stop('DEPENDENCY_OUTSIDE_RELEASE')
        relative=str(dep.relative_to(sources));deps.append(dict(path=relative,sha256=sha(read(sources,relative))))
    emit('DEPENDENCIES',deps)
    rests=[c for c in containers if cname(c)==cname(edge)[:-5]+'-rest']
    if len(rests)!=1: raise Stop('REST_MISSING_OR_AMBIGUOUS')
    db,name=find_db(rests[0],containers)
    emit('DATABASE',dict(container=cname(db),database=name))
    emit('SCHEMA',sql(db,name,"SELECT json_build_object('version',current_setting('server_version'),'columns',(SELECT json_object_agg(column_name,data_type) FROM information_schema.columns WHERE table_schema='public' AND table_name='orders' AND column_name IN ('id','source','external_source','external_id','work','amount','original_amount','order_number','received_date','entrance','floor','intercom','amount_confirmed','work_items','lemana_import_meta')),'manual_number_index',to_regclass('public.orders_manual_number_unique') IS NOT NULL,'triggers',(SELECT json_agg(json_build_object('name',t.tgname,'function',p.proname,'md5',md5(p.prosrc)) ORDER BY t.tgname) FROM pg_trigger t JOIN pg_proc p ON p.oid=t.tgfoid WHERE t.tgrelid='public.orders'::regclass AND NOT t.tgisinternal))"))
    handlers=['mini-app-api','profile-self-api','master-workflow-api','claims-api','integration-api','report-api','order-lifecycle-api']
    for handler in handlers:
        entry=handler+'/supabase/functions/'+handler+'/index.ts'
        if not (sources/entry).is_file():
            emit('HANDLER',dict(name=handler,missing=True));continue
        code=read(sources,entry)
        payroll=handler+'/order-payroll.js'
        item=dict(name=handler,source_sha256=sha(code),payroll_sha256=sha(read(sources,payroll)) if (sources/payroll).is_file() else None,bundle_sha256=sha(read(bundles,handler+'.eszip',32000000)))
        emit('HANDLER',item)
    stages=[BASE/'intake-296-api']+sorted(BASE.glob('service-trial-*/edge'))
    for stage in stages:
        if stage.resolve()!=stage or not stage.is_dir() or not (stage/'cache').is_dir():continue
        current=stage/'bundles/mini-app-api.eszip'
        emit('CACHE',dict(path=str(stage/'cache'),mini_bundle_matches=current.is_file() and current.resolve()==current and sha(current.read_bytes())==sha(read(bundles,'mini-app-api.eszip',32000000))))
    emit('CHECK_ONLY','No files, services or customer data changed')

if __name__=='__main__':
    try: main()
    except (Stop,OSError,ValueError,KeyError) as error:
        print('STOP: '+(str(error) if isinstance(error,Stop) else type(error).__name__),file=sys.stderr);sys.exit(1)
