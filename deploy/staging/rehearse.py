#!/usr/bin/env python3
"""Rehearse the EXISTING frontend release core in a new local scratch directory.

No server/network/Docker/database connection. Never calls the production CLI.
The generated release B is synthetic, not a production release artifact.
"""
import argparse
import copy
import fcntl
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

REPO = Path(__file__).resolve().parents[2]


class Stop(Exception):
    pass


def core():
    spec = importlib.util.spec_from_file_location('staging_release_core', REPO / 'scripts/ru-master-home-release.py')
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


def check_target(root):
    root = Path(root)
    allowed = (Path(tempfile.gettempdir()).resolve(), Path('/workspace/scratch'))
    if (not root.is_absolute() or root.resolve() != root or root.exists() or root.is_symlink() or
            not root.parent.is_dir() or not root.name.startswith('bos-staging-') or
            not any(root.is_relative_to(p) and root != p for p in allowed)):
        raise Stop('NEW_NON_SYMLINK_SCRATCH_TARGET_REQUIRED')


def snapshot(root, c):
    return {p.name: c.digest(p.read_bytes()) for p in root.iterdir() if p.is_file()}


def verify_manifest(root, c):
    meta = c.manifest(c.local_file(root, 'build-version.js').read_bytes())
    if c.digest(c.local_file(root, 'index.html').read_bytes()) != meta['shell']:
        raise Stop('SHELL_HASH_MISMATCH')
    for name, expected in meta['assets'].items():
        if c.digest(c.local_file(root, name).read_bytes()) != expected:
            raise Stop('ASSET_HASH_MISMATCH')
    return meta


def rehearse(root):
    check_target(root)
    # mkdir is exclusive: concurrent or repeated runs cannot reuse another target.
    root.mkdir(mode=0o700)
    lock = open(root / '.lock', 'x')
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        c = core()
        web = root / 'web'
        web.mkdir(mode=0o700)
        names = subprocess.run(['git', 'ls-files', '-z'], cwd=REPO, check=True, capture_output=True).stdout.decode().split('\0')
        for name in names:
            if '/' not in name and Path(name).suffix in ('.html', '.js', '.css', '.png', '.jpg', '.svg', '.ico', '.webmanifest', '.woff', '.woff2', '.webp'):
                shutil.copy2(c.local_file(REPO, name), web / name)
        meta = verify_manifest(web, c)
        original = snapshot(web, c)
        shutil.copytree(web, root / 'frontend-backup')
        shutil.copytree(root / 'frontend-backup', root / 'restored-web')
        verify_manifest(root / 'restored-web', c)
        restored = snapshot(root / 'restored-web', c) == original
        names = ('master-daily-home-v127.js', 'index.html', 'sw.js', 'build-version.js')
        old = {n: c.local_file(web, n).read_bytes() for n in names}
        new = dict(old)
        new[names[0]] += b'\n// LOCAL STAGING REHEARSAL B; NEVER DEPLOY\n'
        build = c.digest(new[names[0]])[:20]
        new['index.html'] = old['index.html'].replace(meta['id'].encode(), build.encode())
        new['sw.js'] = old['sw.js'].replace(meta['id'].encode(), build.encode())
        next_meta = copy.deepcopy(meta)
        next_meta.update(id=build, shell=c.digest(new['index.html']))
        next_meta['assets'][names[0]] = c.digest(new[names[0]])
        new['build-version.js'] = b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD=' + json.dumps(next_meta, separators=(',', ':')).encode() + b';\n'
        revision = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=REPO, capture_output=True, check=True, text=True).stdout.strip()
        record = c.install(web, root / 'successful-release', old, new, revision, lambda _: verify_manifest(web, c))
        if record['status'] != 'deployed':
            raise Stop('RELEASE_NOT_DEPLOYED')
        c.rollback(web, root / 'successful-release', record)
        if snapshot(web, c) != original:
            raise Stop('MANUAL_ROLLBACK_MISMATCH')
        data = root / 'synthetic-business-change.txt'
        data.write_text('created-before-backup')
        def fail(_):
            verify_manifest(web, c)
            data.write_text('created-after-backup')
            raise Stop('CONTROLLED_FAILED_HEALTH_CHECK')
        try:
            c.install(web, root / 'failed-release', old, new, revision, fail)
        except Stop as error:
            if str(error) != 'CONTROLLED_FAILED_HEALTH_CHECK':
                raise
        else:
            raise Stop('FAILURE_NOT_TRIGGERED')
        if snapshot(web, c) != original or data.read_text() != 'created-after-backup':
            raise Stop('AUTOMATIC_ROLLBACK_MISMATCH')
        report = {'scope': 'local-frontend-rehearsal-only', 'source_revision': revision,
            'build_a': meta['id'], 'synthetic_build_b': build,
            'successful_release_and_manual_rollback': True, 'failed_release_and_automatic_rollback': True,
            'separate_frontend_restore_hashes_match': restored, 'post_backup_data_marker_preserved': True,
            'server_staging_ready': False,
            'limitations': ['No HTTP/TLS/PWA deployment, server restart or real database recovery exercised.',
                            'Business-data marker is a file; the separate PGlite rehearsal covers only its partial fixture schema.']}
        c.atomic(root / 'result.json', json.dumps(report, ensure_ascii=False, indent=2).encode())
        return report
    finally:
        lock.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--environment', choices=['staging'], required=True)
    parser.add_argument('--workdir', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='Check target without writing anything')
    args = parser.parse_args()
    if args.check:
        check_target(args.workdir)
        print('LOCAL_REHEARSAL_CHECK_OK; no files written')
    else:
        print(json.dumps(rehearse(args.workdir), indent=2))


if __name__ == '__main__':
    try:
        main()
    except Exception as e:
        # Avoid dumping subprocess output or arbitrary runtime data.
        print('REHEARSAL_FAILED: ' + (str(e) if isinstance(e, Stop) else type(e).__name__), file=sys.stderr)
        sys.exit(1)
