"""Overlay only finance assets onto the actual RU web tree."""
import copy
import json
import re
from common import read, sha, require
import check

EDITED = ('finance-page.js', 'pwa-register.js', 'approved-operations-ui.css')
ADDED = ('finance-export-data.js', 'finance-export-ui.js')
VERSIONS = ('index.html', 'sw.js', 'build-version.js')


def manifest(root):
    raw = read(root / 'build-version.js')
    match = re.fullmatch(rb'// Generated by npm run build\. Do not edit\.\nself\.BOS_BUILD=(\{.*\});\n', raw, re.S)
    require(match is not None, 'MANIFEST_FORMAT')
    meta = json.loads(match[1])
    require(re.fullmatch('[a-f0-9]{20}', meta['id']), 'BUILD_FORMAT')
    require(sha(read(root / 'index.html')) == meta['shell'], 'SHELL_HASH_DIFFERS')
    for filename, expected in meta['assets'].items():
        require(re.fullmatch(r'[A-Za-z0-9_.-]+', filename) and filename not in ('.', '..'), 'ASSET_PATH')
        require(sha(read(root / filename)) == expected, 'ASSET_HASH_DIFFERS_' + filename)
    return meta


def transform(before, current, after):
    require(check.normalized(before) == check.normalized(current), 'SOURCE_BASELINE_DIFFERS')
    if before.rstrip() == current.rstrip(): return after
    # Only the three known base origins may differ. Preserve their exact mapping.
    pattern = re.compile(b'|'.join(re.escape(origin.encode()) for origin in check.ORIGINS))
    old, new = pattern.findall(before), pattern.findall(current)
    require(len(old) == len(new), 'ORIGIN_COUNT_DIFFERS')
    mapping = {}
    for a, b in zip(old, new):
        require(a not in mapping or mapping[a] == b, 'ORIGIN_MAPPING_AMBIGUOUS')
        mapping[a] = b
    apply = lambda data: pattern.sub(lambda m: mapping.get(m.group(), m.group()), data)
    require(apply(before).rstrip() == current.rstrip(), 'SOURCE_TRANSFORM_DIFFERS')
    return apply(after)


def prepare(root, package, before_build, application):
    meta = manifest(root)
    require(meta['id'] == before_build, 'PRODUCTION_BUILD_CHANGED')
    bundles = [read(root / n) for n in meta['assets'] if n.endswith('.bundle.js')]
    # Financial models must still be the verified baseline. RU transport is retained.
    for filename, expected in check.BASELINE['web'].items():
        if filename == 'network-direct-v86.js': continue
        data = check.runtime_source(root, filename, bundles)
        require(data is not None and check.source_hash(data) == expected, 'FINANCE_MODEL_CHANGED_' + filename)
    network = check.runtime_source(root, 'network-direct-v86.js', bundles)
    require(network and b'BOS_RU_NETWORK' in network, 'RU_NETWORK_MISSING')
    new = {}
    for filename in EDITED:
        require(filename in meta['assets'] and filename not in meta.get('assetBundles', {}), 'FINANCE_ASSET_LAYOUT_CHANGED')
        new['web/' + filename] = transform(package['before/' + filename], read(root / filename), package['after/' + filename])
    for filename in ADDED:
        require(not (root / filename).exists() and not (root / filename).is_symlink(), 'NEW_WEB_FILE_EXISTS')
        new['web/' + filename] = package['after/' + filename]
    build = sha((meta['id'] + application + ''.join(n + sha(new[n]) for n in sorted(new))).encode())[:20]
    html = read(root / 'index.html')
    require(before_build.encode() in html, 'HTML_BUILD_MARKER_MISSING')
    new['web/index.html'] = html.replace(before_build.encode(), build.encode())
    worker = read(root / 'sw.js')
    marker = ("const BUILD_ID='" + before_build + "';").encode()
    require(worker.count(marker) == 1, 'WORKER_BUILD_MARKER_CHANGED')
    new['web/sw.js'] = worker.replace(marker, ("const BUILD_ID='" + build + "';").encode())
    updated = copy.deepcopy(meta)
    updated['id'], updated['shell'] = build, sha(new['web/index.html'])
    for filename in EDITED + ADDED:
        updated['assets'][filename] = sha(new['web/' + filename])
    new['web/build-version.js'] = (b'// Generated by npm run build. Do not edit.\nself.BOS_BUILD=' +
                                    json.dumps(updated, ensure_ascii=False, separators=(',', ':')).encode() + b';\n')
    return new, build
