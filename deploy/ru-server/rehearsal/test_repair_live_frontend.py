import hashlib
import json
from pathlib import Path
import re
import tempfile
import unittest
import release_files
import repair_live_frontend as r

class RepairTests(unittest.TestCase):
    def test_patch_changes_only_static_route_and_is_idempotent(self):
        current=release_files.render_caddy(r.ORIGIN,'unused',True)
        old=current.replace(r.NEW_STATIC,r.OLD_STATIC)
        self.assertNotEqual(old,current)
        self.assertEqual(r.patch_config(old),current)
        self.assertEqual(r.patch_config(current),current)
        for bad in ('unrecognized',old+old,old.replace(r.OLD_STATIC,'.*')):
            with self.assertRaises(ValueError):r.patch_config(bad)

    def test_repair_requires_exact_active_manifest_and_preserves_existing_assets(self):
        with tempfile.TemporaryDirectory() as tmp:
            source=Path(tmp)/'build';web=Path(tmp)/'web';source.mkdir();web.mkdir()
            data=b'window.BOS_ASSET_URL = true;'
            (source/'startup-shell.bundle.js').write_bytes(data)
            for p in (source,web):(p/'index.html').write_bytes(b'HTML')
            build={'id':'a'*20,'shell':hashlib.sha256(b'HTML').hexdigest(),
                   'assets':{'startup-shell.bundle.js':hashlib.sha256(data).hexdigest()}}
            raw=('// Generated by npm run build. Do not edit.\nself.BOS_BUILD='+json.dumps(build)+';\n').encode()
            for p in (source,web):(p/'build-version.js').write_bytes(raw)
            digest=hashlib.sha256(raw).hexdigest()
            self.assertEqual(r.missing_assets(source,web,digest),(build,['startup-shell.bundle.js']))
            (web/'startup-shell.bundle.js').write_bytes(data)
            self.assertEqual(r.missing_assets(source,web,digest),(build,[]))
            (web/'startup-shell.bundle.js').write_bytes(b'changed')
            with self.assertRaisesRegex(ValueError,'differs'):r.missing_assets(source,web,digest)
            with self.assertRaisesRegex(ValueError,'differ'):r.missing_assets(source,web,'0'*64)

if __name__=='__main__':unittest.main()
