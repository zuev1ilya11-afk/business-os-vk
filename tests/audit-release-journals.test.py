"""Synthetic files only: python3 tests/audit-release-journals.test.py"""
import contextlib
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import tempfile
import unittest
from unittest import mock

spec = importlib.util.spec_from_file_location('audit_journals', Path(__file__).resolve().parents[1] / 'scripts/audit-release-journals.py')
audit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(audit)
sha = lambda data: hashlib.sha256(data).hexdigest()


class Fixture:
    def __init__(self, directory):
        self.base = Path(directory)
        self.live, self.report, self.price = [self.base / name for name in ('live', 'report', 'price')]
        self.report_build, self.price_build = 'b' * 20, 'c' * 20
        self.records = []
        main = {'index.ts': b'gateway fixture', 'routes.json': b'{"SECRET_BODY":"do-not-print"}'}
        for name, data in main.items():
            self.write('edge/main/' + name, data)
        before_main = {name: {'sha': sha(data), 'mode': 384, 'uid': 0, 'gid': 0} for name, data in main.items()}
        for work, allowed, old_build, build in (
            (self.report, audit.REPORT_ALLOWED, 'a' * 20, self.report_build),
            (self.price, audit.PRICE_ALLOWED, self.report_build, self.price_build)):
            record = {'status': 'applied', 'build': build, 'old_build': old_build,
                      'before': {'main': before_main}, 'files': {}}
            for name in sorted(allowed):
                data = (build + ' ' + name).encode()
                if name == 'web/build-version.js':
                    meta = {'id': build, 'assetBundles': {name: 'startup-shell.bundle.js' for name in audit.WEB}}
                    data = ('// Generated by npm run build. Do not edit.\nself.BOS_BUILD=' + json.dumps(meta) + ';\n').encode()
                previous = self.records[0]['files'].get(name) if self.records else None
                before = previous['after'] if previous else sha(b'old fixture')
                record['files'][name] = {'before': {'sha': before, 'mode': 384, 'uid': 0, 'gid': 0}, 'after': sha(data)}
                self.write(name, data)
            (work / 'stage-fixture').mkdir(parents=True)
            (work / 'current.json').write_text('{"stage":"stage-fixture"}')
            self.records.append(record)
            self.save(len(self.records) - 1)

    def write(self, name, data):
        target = self.live / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)

    def save(self, index):
        work = self.report if index == 0 else self.price
        (work / 'stage-fixture/journal.json').write_text(json.dumps(self.records[index]))

    def verify(self):
        return audit.verify(self.live, self.report, self.price)


class JournalTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.f = Fixture(self.temp.name)

    def test_matching_chain_overrides_older_files_without_writes_or_secret_output(self):
        before = {str(p): p.read_bytes() for p in self.f.base.rglob('*') if p.is_file()}
        out = self.f.verify()
        overlap = 'edge/bundles/report-api.eszip'
        self.assertNotEqual(self.f.records[0]['files'][overlap]['after'], self.f.records[1]['files'][overlap]['after'])
        self.assertTrue(out['VERIFIED'], out)
        self.assertTrue(out['COMPLETE'])
        self.assertTrue(out['CHAIN_MATCH'])
        self.assertEqual(out['LIVE_BUILD'], self.f.price_build)
        self.assertEqual(out['EFFECTIVE_FILES'], out['FILES_MATCHED'])
        self.assertEqual(out['MAIN_FILES'], out['MAIN_MATCHED'])
        self.assertEqual(before, {str(p): p.read_bytes() for p in self.f.base.rglob('*') if p.is_file()})
        with contextlib.redirect_stdout(io.StringIO()) as output:
            status = audit.main(['--live', str(self.f.live), '--report', str(self.f.report), '--price', str(self.f.price)])
        self.assertEqual(status, 0)
        self.assertLessEqual(len(output.getvalue().splitlines()), 15)
        self.assertNotIn('SECRET_BODY', output.getvalue())
        self.assertNotIn(self.temp.name, output.getvalue())

    def test_bundle_and_web_hash_mismatches_are_reported_not_hidden_by_chain(self):
        for path in ('edge/bundles/report-api.eszip', 'web/startup-shell.bundle.js'):
            with self.subTest(path=path):
                original = (self.f.live / path).read_bytes()
                self.f.write(path, b'changed body never printed')
                out = self.f.verify()
                self.assertTrue(out['COMPLETE'])
                self.assertFalse(out['VERIFIED'])
                self.assertIn(path, out['MISMATCHES'])
                self.assertIn('FILE_HASH_MISMATCH', out['ERRORS'])
                self.f.write(path, original)

    def test_missing_file_is_incomplete(self):
        (self.f.live / 'edge/bundles/report-api.eszip').unlink()
        out = self.f.verify()
        self.assertFalse(out['COMPLETE'])
        self.assertIn('FILE_UNREADABLE_OR_MISSING', out['ERRORS'])

    def test_build_and_overlapping_file_chain_mismatches_stop_verification(self):
        self.f.records[1]['old_build'] = 'd' * 20
        self.f.save(1)
        self.assertIn('BUILD_CHAIN_MISMATCH', self.f.verify()['ERRORS'])
        self.f.records[1]['old_build'] = self.f.report_build
        self.f.records[1]['files']['web/index.html']['before']['sha'] = 'e' * 64
        self.f.save(1)
        out = self.f.verify()
        self.assertFalse(out['COMPLETE'])
        self.assertIn('FILE_CHAIN_MISMATCH', out['ERRORS'])

    def test_pointer_traversal_is_rejected(self):
        (self.f.price / 'current.json').write_text('{"stage":"../report/stage-fixture"}')
        out = self.f.verify()
        self.assertFalse(out['COMPLETE'])
        self.assertIn('INVALID_STAGE_POINTER', out['ERRORS'])

    def test_pointer_and_live_symlinks_are_rejected(self):
        pointer = self.f.price / 'current.json'
        data = pointer.read_bytes()
        pointer.unlink()
        pointer.symlink_to(self.f.report / 'current.json')
        self.assertIn('SYMLINK_PATH', self.f.verify()['ERRORS'])
        pointer.unlink()
        pointer.write_bytes(data)
        target = self.f.live / 'edge/bundles/report-api.eszip'
        target.unlink()
        target.symlink_to(self.f.live / 'edge/main/routes.json')
        out = self.f.verify()
        self.assertFalse(out['COMPLETE'])
        self.assertIn('SYMLINK_PATH', out['ERRORS'])

    def test_invalid_sha_namespace_and_omitted_required_file_are_rejected(self):
        path = 'edge/bundles/report-api.eszip'
        original = self.f.records[1]['files'][path]['after']
        self.f.records[1]['files'][path]['after'] = 'not-a-hash'
        self.f.save(1)
        self.assertIn('INVALID_SHA', self.f.verify()['ERRORS'])
        self.f.records[1]['files'][path]['after'] = original
        self.f.records[1]['files']['../../PRIVATE_PATH'] = {'after': original}
        self.f.save(1)
        out = self.f.verify()
        self.assertIn('INVALID_RELEASE_FILES', out['ERRORS'])
        self.assertNotIn('PRIVATE_PATH', json.dumps(out))
        del self.f.records[1]['files']['../../PRIVATE_PATH']
        del self.f.records[1]['files'][path]
        self.f.save(1)
        self.assertIn('INVALID_RELEASE_FILES', self.f.verify()['ERRORS'])

    def test_main_added_changed_and_missing_files_are_detected(self):
        self.f.write('edge/main/private-filename.txt', b'PRIVATE_DATA')
        out = self.f.verify()
        self.assertFalse(out['VERIFIED'])
        self.assertIn('MAIN_EXTRA_FILE', out['ERRORS'])
        self.assertNotIn('private-filename', json.dumps(out))
        (self.f.live / 'edge/main/private-filename.txt').unlink()
        self.f.write('edge/main/index.ts', b'changed main')
        self.assertIn('edge/main/index.ts', self.f.verify()['MISMATCHES'])
        (self.f.live / 'edge/main/index.ts').unlink()
        self.assertFalse(self.f.verify()['COMPLETE'])

    def test_read_and_tree_budgets_are_enforced(self):
        with mock.patch.object(audit, 'MAX_TOTAL', 1):
            out = self.f.verify()
        self.assertIn('READ_BUDGET', out['ERRORS'])
        self.assertFalse(out['COMPLETE'])
        with mock.patch.object(audit, 'MAX_FILES', 1):
            out = self.f.verify()
        self.assertFalse(out['COMPLETE'])
        self.assertIn('INVALID_MAIN_BASELINE', out['ERRORS'])
        self.f.write('edge/main/extra-1.txt', b'x')
        self.f.write('edge/main/extra-2.txt', b'x')
        with mock.patch.object(audit, 'MAX_FILES', 3):
            out = self.f.verify()
        self.assertIn('TREE_BUDGET', out['ERRORS'])
        with mock.patch.object(audit, 'MAX_FILE', 1):
            out = self.f.verify()
        self.assertFalse(out['COMPLETE'])
        self.assertIn('READ_BUDGET', out['ERRORS'])

    def test_read_error_is_sanitized_and_does_not_claim_complete(self):
        original = audit.os.open
        target = self.f.live / 'edge/bundles/report-api.eszip'
        def denied(path, *args, **kwargs):
            if path == target:
                raise PermissionError('PASSWORD=PRIVATE_SENTINEL')
            return original(path, *args, **kwargs)
        with mock.patch.object(audit.os, 'open', side_effect=denied):
            out = self.f.verify()
        self.assertFalse(out['COMPLETE'])
        self.assertNotIn('PRIVATE_SENTINEL', json.dumps(out))
        self.assertIn('FILE_UNREADABLE_OR_MISSING', out['ERRORS'])

    def test_live_build_and_nonapplied_status_and_duplicate_json_are_rejected(self):
        path = self.f.live / 'web/build-version.js'
        original = path.read_bytes()
        path.write_bytes(original.replace(self.f.price_build.encode(), b'd' * 20))
        self.assertIn('LIVE_BUILD_MISMATCH', self.f.verify()['ERRORS'])
        path.write_bytes(original)
        self.f.records[1]['status'] = 'verified'
        self.f.save(1)
        self.assertIn('RELEASE_NOT_APPLIED', self.f.verify()['ERRORS'])
        (self.f.price / 'current.json').write_text('{"stage":"stage-fixture","stage":"stage-other"}')
        self.assertIn('DUPLICATE_JSON_KEY', self.f.verify()['ERRORS'])

    def test_mismatch_paths_are_capped(self):
        for path in sorted(self.f.records[1]['files']):
            if path != 'web/build-version.js':
                self.f.write(path, b'bad')
        out = self.f.verify()
        self.assertGreater(out['MISMATCH_COUNT'], 5)
        self.assertEqual(len(out['MISMATCHES']), 5)
        self.assertTrue(all(path in audit.DISPLAY for path in out['MISMATCHES']))


if __name__ == '__main__':
    unittest.main()
