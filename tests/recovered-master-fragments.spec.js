const {test,expect}=require('@playwright/test');
const {fullStack}=require('./helpers/full-stack.cjs');

test('recovered deduction actions preserve draft, files, validation and synthetic order at 390px',async({page},testInfo)=>{
 const {db}=await fullStack(page,'master');
 Object.assign(db.tables.orders[0],{source:'Телефон',original_amount:10000,amount:10000,master_workflow_stage:'started'});
 await page.setViewportSize({width:390,height:844});
 await page.goto('/');await expect(page.locator('#authGate')).toBeHidden();
 await page.waitForFunction(()=>window.BOS_ORDER_LIFECYCLE_V106===true);
 await page.evaluate(()=>openMasterReportForm('11'));
 await page.locator('#mrAct').setInputFiles({name:'synthetic-act.pdf',mimeType:'application/pdf',buffer:Buffer.from('synthetic act')});
 await page.locator('#mrPhotos').setInputFiles({name:'synthetic-photo.png',mimeType:'image/png',buffer:Buffer.from('synthetic photo')});
 const before=structuredClone(db.tables.orders);
 const orderWrites=()=>db.calls.filter(c=>c.table==='orders'&&['update','insert','delete'].includes(c.mode)).length;
 const writes=orderWrites();
 await page.locator('label').filter({has:page.locator('[name=mrAllDone][value=false]')}).click();
 const dialog=page.locator('#mrDeductionDialog');await expect(dialog).toBeVisible();
 await expect(dialog.locator('.eyebrow')).toHaveText('№ 11 · РЕЗУЛЬТАТ РАБОТ');
 await expect(dialog.getByLabel('Причина',{exact:true})).toBeVisible();
 await expect(dialog.getByRole('button',{name:'Добавить в отчёт',exact:true})).toBeVisible();
 await page.screenshot({path:testInfo.outputPath('recovered-deduction-empty-390.png'),fullPage:true});
 await page.locator('#mrDeductionContinue').click();await expect(page.locator('#mrDeductionError')).not.toBeEmpty();
 await page.locator('#mrAddCatalog').click();await page.locator('#mrCatalogSearch').fill('бленды');
 await page.locator('[data-service=standard_016]').click();await page.locator('[data-qty="0"]').fill('1.5');
 await page.locator('#mrDeductionComment').fill('Синтетическая причина');
 await expect(page.locator('#mrDeductionTotal')).toContainText('450');
 await expect(page.locator('#mrAfterDeduction')).toContainText('9 550');
 await dialog.getByRole('button',{name:'Отмена',exact:true}).click();await expect(dialog).not.toBeVisible();
 await page.locator('#mrEditDeduction').click();await expect(dialog).toBeVisible();
 await expect(page.locator('[data-qty="0"]')).toHaveValue('1.5');
 await expect(page.locator('#mrDeductionComment')).toHaveValue('Синтетическая причина');
 await page.locator('#mrDeductionContinue').scrollIntoViewIfNeeded();
 expect(await dialog.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1);
 await page.screenshot({path:testInfo.outputPath('recovered-deduction-selected-390.png'),fullPage:true});
 await page.locator('#mrDeductionContinue').click();await expect(dialog).not.toBeVisible();
 await expect(page.locator('#mrEditDeduction')).toBeFocused();
 const payload=await page.locator('#masterReportForm').evaluate(f=>f.bosDeductionPayload());
 expect(payload.uncompleted_work_amount).toBe(450);expect(payload.uncompleted_work_items[0].quantity).toBe(1.5);
 expect(payload.uncompleted_work_description).toBe('Синтетическая причина');
 expect(await page.locator('#mrAct').evaluate(e=>e.files[0].name)).toBe('synthetic-act.pdf');
 expect(await page.locator('#mrPhotos').evaluate(e=>e.files[0].name)).toBe('synthetic-photo.png');
 expect(db.tables.orders).toEqual(before);
 expect(orderWrites()).toBe(writes);
});
