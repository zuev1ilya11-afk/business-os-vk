"""Run: python3 tests/audit-production-readonly.test.py"""
import contextlib
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import tempfile
import unittest
from unittest import mock

spec = importlib.util.spec_from_file_location('audit_readonly', Path(__file__).resolve().parents[1] / 'scripts/audit-production-readonly.py')
audit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(audit)


class ReadOnlyAuditTests(unittest.TestCase):
    def test_manifest_identity_and_corruption_are_detected_without_writes(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / 'app.js').write_bytes(b'fixture')
            (root / 'index.html').write_bytes(b'<p>fixture</p>')
            sha = lambda b: hashlib.sha256(b).hexdigest()
            manifest = {'id': '1234567890abcdef', 'assets': {'app.js': sha(b'fixture')}, 'shell': sha(b'<p>fixture</p>')}
            (root / 'build-version.js').write_text('// Generated by npm run build. Do not edit.\nself.BOS_BUILD=' + json.dumps(manifest) + ';\n')
            before = {p.name: p.read_bytes() for p in root.iterdir()}
            result = audit.web_identity(root, [0])
            self.assertEqual(result['assets_verified'], 1)
            self.assertTrue(result['shell_matches'])
            self.assertEqual(before, {p.name: p.read_bytes() for p in root.iterdir()})
            (root / 'app.js').write_bytes(b'changed')
            self.assertEqual(audit.web_identity(root, [0])['mismatches'][0]['asset'], 'app.js')

    def test_path_escape_and_symlinks_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / 'file.js').write_bytes(b'fixture')
            (root / 'link.js').symlink_to(root / 'file.js')
            for name in ('../file.js', str(root / 'file.js'), 'link.js'):
                with self.assertRaises(audit.ProbeError):
                    audit.hash_file(root, name, [0])

    def test_size_budget_is_enforced(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / 'file.js').write_bytes(b'fixture')
            with self.assertRaises(audit.ProbeError):
                audit.hash_file(root, 'file.js', [audit.MAX_TOTAL])

    def test_git_does_not_print_remote_credentials_or_changed_filenames(self):
        responses = ['a' * 40, ' M confidential-customer-name.txt', 'https://username:secret@github.com/zuev1ilya11-afk/business-os-vk.git']
        with tempfile.TemporaryDirectory() as tmp, mock.patch.object(audit, 'command', side_effect=responses) as command:
            result = audit.git_identity(tmp)
        encoded = json.dumps(result)
        self.assertNotIn('secret', encoded)
        self.assertNotIn('customer-name', encoded)
        self.assertEqual(result['tracked_changes'], 1)
        self.assertTrue(result['expected_github_remote'])
        self.assertTrue(all('--no-optional-locks' in call.args[0] for call in command.call_args_list))

    def test_docker_reads_no_env_or_log_body_and_does_not_print_host_path(self):
        fields = ['b' * 64, '/bos-fixture-edge', 'sha256:' + 'c' * 64, 'fixture/edge:1', 'running', 'healthy',
                  [{'Destination': '/bos-main', 'Type': 'bind', 'Source': '/private/secret-path', 'RW': True}]]
        with mock.patch.object(audit, 'command', side_effect=['abcdef123456\tbos-fixture-edge', '\t'.join(json.dumps(f) for f in fields)]) as command:
            result = audit.inspect_containers([0])
        self.assertNotIn('secret-path', json.dumps(result))
        args = command.call_args_list[-1].args[0]
        self.assertIn('inspect', args)
        self.assertNotIn('.Env', args[args.index('--format') + 1])
        self.assertNotIn('logs', args)
        self.assertEqual(result['containers'][0]['health'], 'healthy')

    def test_database_queries_metadata_only_and_use_readonly_transactions(self):
        calls = []
        def fake(args):
            calls.append(args)
            return json.dumps({'migration_table_present': True}) if len(calls) == 1 else '["20261111000000"]'
        with mock.patch.object(audit, 'command', side_effect=fake):
            result = audit.database_identity('bos-db', 'postgres')
        self.assertFalse(result['business_rows_read'])
        self.assertEqual(len(calls), 2)
        for args in calls:
            self.assertEqual(args[:3], ['docker', 'exec', 'bos-db'])
            self.assertIn('BEGIN READ ONLY', args[-1])
            self.assertIn('ROLLBACK', args[-1])
            for verb in ('UPDATE ', 'DELETE ', 'INSERT ', 'ALTER ', 'CREATE ', 'DROP '):
                self.assertNotIn(verb, args[-1])
        with self.assertRaises(audit.ProbeError):
            audit.database_identity('--privileged', 'postgres; drop')

    def test_command_failure_does_not_reveal_stderr(self):
        failed = type('Result', (), {'returncode': 1, 'stdout': b'', 'stderr': b'SECRET=never-output'})()
        with mock.patch.object(audit.subprocess, 'run', return_value=failed):
            result = audit.guarded(lambda: audit.command(['docker', 'ps']))
        self.assertEqual(result, {'status': 'unavailable', 'reason': 'COMMAND_FAILED'})
        self.assertNotIn('SECRET', json.dumps(result))

    def test_default_never_accesses_database(self):
        with mock.patch.object(audit, 'git_identity', return_value={}), mock.patch.object(audit, 'inspect_containers', return_value={}), mock.patch.object(audit, 'database_identity') as database, contextlib.redirect_stdout(io.StringIO()) as stdout:
            self.assertEqual(audit.main([]), 0)
        database.assert_not_called()
        self.assertEqual(json.loads(stdout.getvalue())['database']['status'], 'not_requested')


if __name__ == '__main__':
    unittest.main()
