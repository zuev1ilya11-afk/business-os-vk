spec = importlib.util.spec_from_file_location('audit_readonly', Path(__file__).resolve().parents[1] / 'scripts/audit-production-readonly.py')
audit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(audit)


def docker_row(name, health=None, mounts=None):
    fields = ['a' * 64, '/' + name, 'sha256:' + 'c' * 64,
              'fixture/edge:1', 'running', health, mounts or []]
    return '\t'.join(json.dumps(field) for field in fields)


def write_web_fixture(root):
    files = {'app.js': b'fixture', 'index.html': b'<p>fixture</p>', 'sw.js': b'worker'}
    for name, data in files.items():
        (root / name).write_bytes(data)
    manifest = {'id': '1234567890abcdef',
                'assets': {'app.js': hashlib.sha256(files['app.js']).hexdigest()},
                'shell': hashlib.sha256(files['index.html']).hexdigest()}
    (root / 'build-version.js').write_text('// Generated by npm run build. Do not edit.\nself.BOS_BUILD=' + json.dumps(manifest) + ';\n')
    return manifest['id']


class ReadOnlyAuditTests(unittest.TestCase):
    def test_manifest_identity_and_corruption_are_detected_without_writes(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / 'app.js').write_bytes(b'fixture')
            (root / 'index.html').write_bytes(b'<p>fixture</p>')
            sha = lambda b: hashlib.sha256(b).hexdigest()
            manifest = {'id': '1234567890abcdef', 'assets': {'app.js': sha(b'fixture')}, 'shell': sha(b'<p>fixture</p>')}
            (root / 'build-version.js').write_text('// Generated by npm run build. Do not edit.\nself.BOS_BUILD=' + json.dumps(manifest) + ';\n')
            before = {p.name: p.read_bytes() for p in root.iterdir()}
            result = audit.web_identity(root, [0])
            self.assertEqual(result['assets_verified'], 1)
            self.assertTrue(result['shell_matches'])
            self.assertEqual(before, {p.name: p.read_bytes() for p in root.iterdir()})
            (root / 'app.js').write_bytes(b'changed')
            self.assertEqual(audit.web_identity(root, [0])['mismatches'][0]['asset'], 'app.js')

    def test_path_escape_and_symlinks_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / 'file.js').write_bytes(b'fixture')
            (root / 'link.js').symlink_to(root / 'file.js')
            for name in ('../file.js', str(root / 'file.js'), 'link.js'):
                with self.assertRaises(audit.ProbeError):
                    audit.hash_file(root, name, [0])

    def test_size_budget_is_enforced(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / 'file.js').write_bytes(b'fixture')
            with self.assertRaises(audit.ProbeError):
                audit.hash_file(root, 'file.js', [audit.MAX_TOTAL])

    def test_git_does_not_print_remote_credentials_or_changed_filenames(self):
        responses = ['a' * 40, ' M confidential-customer-name.txt', 'https://username:secret@github.com/zuev1ilya11-afk/business-os-vk.git']
        with tempfile.TemporaryDirectory() as tmp, mock.patch.object(audit, 'command', side_effect=responses) as command:
            result = audit.git_identity(tmp)
        encoded = json.dumps(result)
        self.assertNotIn('secret', encoded)
        self.assertNotIn('customer-name', encoded)
        self.assertEqual(result['tracked_changes'], 1)
        self.assertTrue(result['expected_github_remote'])
        self.assertTrue(all('--no-optional-locks' in call.args[0] for call in command.call_args_list))

    def test_docker_reads_no_env_or_log_body_and_does_not_print_host_path(self):
        fields = ['b' * 64, '/bos-fixture-edge', 'sha256:' + 'c' * 64, 'fixture/edge:1', 'running', 'healthy',
                  [{'Destination': '/bos-main', 'Type': 'bind', 'Source': '/private/secret-path', 'RW': True}]]
        with mock.patch.object(audit, 'command', side_effect=['abcdef123456\tbos-fixture-edge', '\t'.join(json.dumps(f) for f in fields)]) as command:
            result = audit.inspect_containers([0])
        self.assertNotIn('secret-path', json.dumps(result))
        args = command.call_args_list[-1].args[0]
        self.assertIn('inspect', args)
        self.assertNotIn('.Env', args[args.index('--format') + 1])
        self.assertNotIn('logs', args)
        self.assertEqual(result['containers'][0]['health'], 'healthy')

    def test_one_failed_inspection_preserves_other_containers_and_web_build(self):
        web, failed, edge = 'a' * 12, 'b' * 12, 'c' * 12
        names = {web: 'bos-web', failed: 'bos-disappeared', edge: 'bos-edge'}
        for order in ((failed, web, edge), (web, failed, edge), (web, edge, failed)):
            with self.subTest(order=order), tempfile.TemporaryDirectory() as tmp:
                root = Path(tmp)
                build = write_web_fixture(root)
                before = {p.name: p.read_bytes() for p in root.iterdir()}

                def fake_run(args, **kwargs):
                    if args[:2] == ['docker', 'ps']:
                        output = '\n'.join(cid + '\t' + names[cid] for cid in order)
                    elif args[-1] == failed:
                        return type('Result', (), {'returncode': 1, 'stdout': b'PARTIAL_SECRET', 'stderr': b'SECRET=never-output'})()
                    elif args[-1] == web:
                        output = docker_row(names[web], mounts=[{'Destination': '/srv', 'Type': 'bind', 'Source': str(root), 'RW': False}])
                    else:
                        output = docker_row(names[edge], 'healthy')
                    return type('Result', (), {'returncode': 0, 'stdout': output.encode(), 'stderr': b''})()

                with mock.patch.object(audit.subprocess, 'run', side_effect=fake_run):
                    result = audit.inspect_containers([0])
                items = {item['name']: item for item in result['containers']}
                self.assertEqual(items['bos-web']['web']['build_id'], build)
                self.assertTrue(items['bos-web']['web']['shell_matches'])
                self.assertEqual(items['bos-edge']['health'], 'healthy')
                self.assertEqual(items['bos-disappeared']['reason'], 'COMMAND_FAILED')
                self.assertEqual(result['matching_containers'], 3)
                self.assertEqual(result['inspected_containers'], 2)
                self.assertEqual(result['failed_containers'], 1)
                self.assertFalse(result['complete'])
                self.assertFalse(result['truncated'])
                self.assertNotIn('SECRET', json.dumps(result))
                self.assertNotIn(str(root), json.dumps(result))
                self.assertEqual(before, {p.name: p.read_bytes() for p in root.iterdir()})

    def test_health_status_is_separate_from_inspection_completeness(self):
        ids = ['a' * 12, 'b' * 12, 'c' * 12]
        names = ['bos-no-healthcheck', 'bos-healthy', 'bos-unhealthy']
        responses = ['\n'.join(cid + '\t' + name for cid, name in zip(ids, names))]
        responses += [docker_row(name, health) for name, health in zip(names, (None, 'healthy', 'unhealthy'))]
        with mock.patch.object(audit, 'command', side_effect=responses):
            result = audit.inspect_containers([0])
        self.assertEqual([row['health'] for row in result['containers']], [None, 'healthy', 'unhealthy'])
        self.assertTrue(result['complete'])
        self.assertEqual(result['failed_containers'], 0)

    def test_malformed_container_metadata_does_not_hide_the_next_container(self):
        for invalid in ('not-json', docker_row('bos-bad', mounts=['not-a-mount'])):
            with self.subTest(invalid=invalid):
                responses = ['aaaaaaaaaaaa\tbos-bad\nbbbbbbbbbbbb\tbos-good', invalid, docker_row('bos-good')]
                with mock.patch.object(audit, 'command', side_effect=responses):
                    result = audit.inspect_containers([0])
                self.assertEqual(result['failed_containers'], 1)
                self.assertEqual(result['containers'][0]['status'], 'unavailable')
                self.assertEqual(result['containers'][1]['name'], 'bos-good')
                self.assertFalse(result['complete'])

    def test_unreadable_artifact_keeps_container_metadata_but_is_incomplete(self):
        responses = ['aaaaaaaaaaaa\tbos-web', docker_row('bos-web', mounts=[
            {'Destination': '/srv', 'Type': 'bind', 'Source': '/private/nonexistent-fixture', 'RW': False}])]
        with mock.patch.object(audit, 'command', side_effect=responses):
            result = audit.inspect_containers([0])
        self.assertEqual(result['containers'][0]['state'], 'running')
        self.assertEqual(result['containers'][0]['web']['status'], 'unavailable')
        self.assertEqual(result['failed_containers'], 0)
        self.assertEqual(result['incomplete_artifact_containers'], 1)
        self.assertFalse(result['complete'])
        self.assertNotIn('/private', json.dumps(result))

    def test_unreadable_web_asset_or_shell_marks_evidence_incomplete(self):
        for filename in ('app.js', 'index.html'):
            with self.subTest(filename=filename), tempfile.TemporaryDirectory() as tmp:
                root = Path(tmp)
                build = write_web_fixture(root)
                original_open = Path.open

                def deny_selected(path, *args, **kwargs):
                    if path == root / filename:
                        raise PermissionError('PRIVATE_SENTINEL ' + str(root))
                    return original_open(path, *args, **kwargs)

                responses = ['aaaaaaaaaaaa\tbos-web', docker_row('bos-web', mounts=[
                    {'Destination': '/srv', 'Type': 'bind', 'Source': str(root), 'RW': False}])]
                with mock.patch.object(audit, 'command', side_effect=responses), mock.patch.object(Path, 'open', deny_selected):
                    result = audit.inspect_containers([0])
                web = result['containers'][0]['web']
                self.assertEqual(web['build_id'], build)
                self.assertFalse(result['complete'])
                self.assertEqual(result['failed_containers'], 0)
                self.assertEqual(result['incomplete_artifact_containers'], 1)
                unavailable = web['mismatches'][0] if filename == 'app.js' else web['shell']
                self.assertEqual(unavailable['status'], 'unavailable')
                self.assertEqual(unavailable['reason'], 'INVALID_OR_UNREADABLE_METADATA')
                self.assertNotIn('PRIVATE_SENTINEL', json.dumps(result))
                self.assertNotIn(str(root), json.dumps(result))

    def test_known_web_hash_mismatch_is_complete_evidence(self):
        for filename in ('app.js', 'index.html'):
            with self.subTest(filename=filename), tempfile.TemporaryDirectory() as tmp:
                root = Path(tmp)
                write_web_fixture(root)
                changed = b'known changed fixture'
                (root / filename).write_bytes(changed)
                responses = ['aaaaaaaaaaaa\tbos-web', docker_row('bos-web', mounts=[
                    {'Destination': '/srv', 'Type': 'bind', 'Source': str(root), 'RW': False}])]
                with mock.patch.object(audit, 'command', side_effect=responses):
                    result = audit.inspect_containers([0])
                self.assertTrue(result['complete'])
                self.assertEqual(result['incomplete_artifact_containers'], 0)
                web = result['containers'][0]['web']
                evidence = web['mismatches'][0] if filename == 'app.js' else web['shell']
                self.assertEqual(evidence['sha256'], hashlib.sha256(changed).hexdigest())
                if filename == 'app.js':
                    self.assertEqual(evidence['status'], 'hash_mismatch')
                    self.assertTrue(web['shell_matches'])
                else:
                    self.assertFalse(web['shell_matches'])

    def test_container_limit_is_reported_as_incomplete(self):
        rows = '\n'.join(f'{number:012x}\tbos-fixture-{number}' for number in range(41))
        with mock.patch.object(audit, 'command', return_value=rows), mock.patch.object(audit, 'inspect_container', return_value={'name': 'bos-fixture'}) as inspect:
            result = audit.inspect_containers([0])
        self.assertEqual(inspect.call_count, 40)
        self.assertEqual(result['matching_containers'], 41)
        self.assertTrue(result['truncated'])
        self.assertFalse(result['complete'])

    def test_database_queries_metadata_only_and_use_readonly_transactions(self):
        calls = []
        def fake(args):
            calls.append(args)
            return json.dumps({'migration_table_present': True}) if len(calls) == 1 else '["20261111000000"]'
        with mock.patch.object(audit, 'command', side_effect=fake):
            result = audit.database_identity('bos-db', 'postgres')
        self.assertFalse(result['business_rows_read'])
        self.assertEqual(len(calls), 2)
        for args in calls:
            self.assertEqual(args[:3], ['docker', 'exec', 'bos-db'])
            self.assertIn('BEGIN READ ONLY', args[-1])
            self.assertIn('ROLLBACK', args[-1])
            for verb in ('UPDATE ', 'DELETE ', 'INSERT ', 'ALTER ', 'CREATE ', 'DROP '):
                self.assertNotIn(verb, args[-1])
        with self.assertRaises(audit.ProbeError):
            audit.database_identity('--privileged', 'postgres; drop')

    def test_command_failure_does_not_reveal_stderr(self):
        failed = type('Result', (), {'returncode': 1, 'stdout': b'', 'stderr': b'SECRET=never-output'})()
        with mock.patch.object(audit.subprocess, 'run', return_value=failed):
            result = audit.guarded(lambda: audit.command(['docker', 'ps']))
        self.assertEqual(result, {'status': 'unavailable', 'reason': 'COMMAND_FAILED'})
        self.assertNotIn('SECRET', json.dumps(result))

    def test_default_never_accesses_database(self):
        with mock.patch.object(audit, 'git_identity', return_value={}), mock.patch.object(audit, 'inspect_containers', return_value={}), mock.patch.object(audit, 'database_identity') as database, contextlib.redirect_stdout(io.StringIO()) as stdout:
            self.assertEqual(audit.main([]), 0)
        database.assert_not_called()
        self.assertEqual(json.loads(stdout.getvalue())['database']['status'], 'not_requested')


