const {test,expect}=require('@playwright/test');
const {fullStack}=require('./helpers/full-stack.cjs');

for(const width of [390,1440])test(`master opens schedule from profile and saves working hours at ${width}`,async({page})=>{
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width,height:900});
  await page.clock.setFixedTime(new Date('2026-10-08T09:00:00Z'));
  const {db,master}=await fullStack(page,'master');
  const preserved={id:'next-day',staff_id:master.id,work_date:'2026-10-10',is_working:true,work_start:'11:00',work_end:'19:00'};
  const other={id:'other-master',staff_id:'another-master',work_date:'2026-10-09',is_working:true,work_start:'10:00',work_end:'20:00'};
  db.tables.staff_schedule.push({...preserved},{...other});
  await page.goto('/');
  await expect(page.locator('#authGate')).toBeHidden();
  await page.locator('#profileBtn').click();
  const entry=page.locator('.bosProfileMenu').getByRole('button',{name:/Мой рабочий график/});
  await expect(entry).toBeVisible();
  await entry.click();
  await expect(page.locator('#bosMasterWorkCalendar')).toBeVisible();
  expect(db.tables.staff_schedule).toEqual([preserved,other]);
  await page.getByRole('button',{name:'Изменить дни',exact:true}).click();
  await page.getByLabel('Выбранный рабочий день').fill('2026-10-09');
  await page.locator('#usWorking').check();
  await page.locator('#usStart').selectOption('14:00');
  await page.locator('#usEnd').selectOption('18:00');
  await page.getByRole('button',{name:'Сохранить график',exact:true}).click();
  const saved=()=>db.tables.staff_schedule.find(r=>r.staff_id===master.id&&r.work_date==='2026-10-09');
  await expect.poll(saved).toMatchObject({is_working:true,work_start:'14:00',work_end:'18:00'});
  await expect(page.locator('#usSaveMsg')).not.toContainText('Сохраняем');
  expect(db.tables.staff_schedule.find(r=>r.id===preserved.id)).toMatchObject(preserved);
  expect(db.tables.staff_schedule.find(r=>r.id===other.id)).toEqual(other);
  await page.reload();
  await expect(page.locator('#authGate')).toBeHidden();
  await page.locator('#profileBtn').click();
  await entry.click();
  await page.locator('.usDay[data-date="2026-10-09"]').click();
  await expect(page.locator('#usWorking')).toBeChecked();
  await expect(page.locator('#usStart')).toHaveValue('14:00');
  await expect(page.locator('#usEnd')).toHaveValue('18:00');
  expect(errors).toEqual([]);
});
