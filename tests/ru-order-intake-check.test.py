import contextlib
import importlib.util
import io
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('check',ROOT/'scripts/ru-order-intake-check.py')
p=importlib.util.module_from_spec(spec);spec.loader.exec_module(p)

class CheckTests(unittest.TestCase):
    def test_schema_queries_are_read_only_and_do_not_print_configuration(self):
        calls=[]
        with patch.object(p,'run',side_effect=lambda args: calls.append(args) or '{"version":"17.11"}'):
            self.assertEqual(p.sql({'Id':'db'},'postgres',"SELECT json_build_object('version',current_setting('server_version'))"),{'version':'17.11'})
            self.assertIn('BEGIN READ ONLY;',calls[0][-1]);self.assertIn("statement_timeout='5s'",calls[0][-1])
            with self.assertRaises(p.Stop):p.sql({'Id':'db'},'postgres','UPDATE orders SET amount=0')
            self.assertEqual(len(calls),1)

    def test_bad_command_does_not_expose_stderr_or_environment(self):
        import subprocess
        with patch.object(p.subprocess,'run',return_value=subprocess.CompletedProcess([],1,'secret stdout','secret password')):
            with self.assertRaisesRegex(p.Stop,'COMMAND_FAILED_EXIT_1') as caught:p.run(['docker','inspect','fixture'])
            self.assertNotIn('secret',str(caught.exception))

    def test_file_reads_reject_symlinks_and_parent_escape(self):
        with tempfile.TemporaryDirectory() as folder:
            root=Path(folder);(root/'a').write_text('safe');(root/'link').symlink_to(root/'a')
            self.assertEqual(p.read(root,'a'),b'safe')
            for name in ['../secret','link']:
                with self.assertRaises(p.Stop):p.read(root,name)

    def test_complete_check_reports_only_version_and_schema_metadata(self):
        with tempfile.TemporaryDirectory() as folder:
            parent=Path(folder);release=parent/'release-test';sources=release/'edge/sources';bundles=release/'edge/bundles';web=release/'web'
            for path in [sources,bundles,web]:path.mkdir(parents=True,exist_ok=True)
            code=(ROOT/'supabase/functions/mini-app-api/index.ts').read_bytes();entry=sources/'mini-app-api/supabase/functions/mini-app-api/index.ts';entry.parent.mkdir(parents=True);entry.write_bytes(code)
            for relative in ['mini-app-api/order-payroll.js','mini-app-api/finance-expenses.js','mini-app-api/supabase/functions/_shared/hands-details.ts']:
                path=sources/relative;path.parent.mkdir(parents=True,exist_ok=True);path.write_text('// fixture public code')
            (bundles/'mini-app-api.eszip').write_bytes(b'fixture bundle')
            (web/'index.html').write_text('<html></html>');(web/'app.js').write_text('// fixture')
            manifest={'id':'fixture','assets':{'app.js':p.sha(b'// fixture')},'shell':p.sha(b'<html></html>')}
            (web/'build-version.js').write_text('// Generated by npm run build. Do not edit.\nself.BOS_BUILD='+json.dumps(manifest)+';\n')
            def mount(source,dest):return {'Type':'bind','Source':str(source),'Destination':dest}
            containers=[{'Id':'edge','Name':'/bos-release-test-edge','Mounts':[mount(sources,'/bos-src'),mount(bundles,'/bos-bundles')]},
                {'Id':'web','Name':'/bos-release-test-https','Mounts':[mount(web,'/srv')]},
                {'Id':'rest','Name':'/bos-release-test-rest','Config':{'Env':['PGRST_DB_URI=postgres://user:DO_NOT_PRINT@db:5432/postgres']},'NetworkSettings':{'Networks':{'local':{}}}},
                {'Id':'db','Name':'/fixture-db','NetworkSettings':{'Networks':{'local':{'Aliases':['db']}}}}]
            commands=[]
            def run(args):
                commands.append(args)
                if args[:3]==['docker','ps','-q']:return 'edge web rest db'
                if args[:2]==['docker','inspect']:return json.dumps(containers)
                if args[:2]==['docker','exec']:
                    self.assertIn('BEGIN READ ONLY;',args[-1]);self.assertIn('information_schema.columns',args[-1]);return '{"version":"17.11","columns":{"id":"uuid"}}'
                raise AssertionError(args)
            out=io.StringIO()
            with patch.object(p,'BASE',parent),patch.object(p,'run',side_effect=run),contextlib.redirect_stdout(out):p.main()
            result=out.getvalue();self.assertIn('"target":true',result);self.assertIn('"integrity":true',result);self.assertIn('CHECK_ONLY=',result)
            self.assertNotIn('DO_NOT_PRINT',result);self.assertNotIn('postgres://',result)
            self.assertTrue(all(args[1] in ['ps','inspect','exec'] for args in commands))

if __name__=='__main__':unittest.main()
