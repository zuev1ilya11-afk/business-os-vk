// Package existing classic scripts in their original order. No minification or rewriting.
const fs=require('node:fs'),path=require('node:path');
module.exports=root=>{
 const config=path.join(root,'scripts/startup-assets.json');
 if(!fs.existsSync(config))return {output:{},assetBundles:{},html:text=>text};
 const {shell}=JSON.parse(fs.readFileSync(config,'utf8'));
 if(!Array.isArray(shell)||!shell.length||new Set(shell).size!==shell.length)throw Error('Invalid startup asset order');
 const loader=fs.readFileSync(path.join(root,'pwa-register.js'),'utf8');
 const eager=loader.match(/const eagerScripts=\[([\s\S]*?)\];/);
 if(!eager)throw Error('Missing eager script list');
 const extra=[...eager[1].matchAll(/'\.\/([^']+\.js)'/g)].map(match=>match[1]).filter(name=>!shell.includes(name));
 const output={},assetBundles={};
 for(const [bundle,names] of [['startup-shell.bundle.js',shell],['startup-eager.bundle.js',extra]]){
  if(!names.length||new Set(names).size!==names.length)throw Error('Invalid asset bundle: '+bundle);
  output[bundle]='// Generated by npm run build. Edit the original source files.\n';
  for(const name of names){
   if(!/^[a-zA-Z0-9_-]+\.js$/.test(name)||assetBundles[name]||['build-version.js','pwa-register.js','sw.js'].includes(name))throw Error('Invalid bundled source: '+name);
   const source=fs.readFileSync(path.join(root,name),'utf8');
   assetBundles[name]=bundle;
   output[bundle]+='\n;\n// Source: '+name+'\n'+source+'\n';
  }
  output[bundle]+=';\n';
 }
 return {output,assetBundles,html:text=>{
  const tags=[...text.matchAll(/<script defer src="([^"?]+)(?:\?[^\"]*)?"><\/script>/g)];
  const current=tags.map(match=>match[1]);
  const original=['build-version.js',...shell,'pwa-register.js'];
  const bundled=['build-version.js','startup-shell.bundle.js','pwa-register.js'];
  if(JSON.stringify(current)!==JSON.stringify(original)&&JSON.stringify(current)!==JSON.stringify(bundled))throw Error('Startup HTML script order differs from the bundle manifest');
  const joined=tags.map(match=>match[0]).join('');
  if(!text.includes(joined))throw Error('Startup scripts must be contiguous');
  return text.replace(joined,bundled.map(name=>'<script defer src="'+name+'"></script>').join(''));
 }};
};
