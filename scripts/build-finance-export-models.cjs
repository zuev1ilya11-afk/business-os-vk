// Keep the export's UI read models local to their module. Existing API globals
// can legitimately be an older deployment and must not be replaced on import.
const fs=require('node:fs'),path=require('node:path'),{buildSync}=require('esbuild');
const root=path.resolve(__dirname,'..');
const output=path.join(root,'supabase/functions/_shared/finance-export-models.mjs');
function generate(){return buildSync({
 absWorkingDir:root,
 stdin:{contents:"import projections from './finance-export-data.js';\nimport workbook from './supabase/functions/_shared/finance-xlsx.js';\nexport { projections, workbook };",resolveDir:root,sourcefile:'finance-export-models-entry.mjs'},
 bundle:true,write:false,format:'esm',platform:'neutral',target:'es2022',charset:'utf8',
 banner:{js:'// Generated by scripts/build-finance-export-models.cjs. Do not edit.\n// Private copies of the unchanged UI read models; no API global assignments.'},
}).outputFiles[0].text;}
if(require.main===module){
 const text=generate();
 if(process.argv.includes('--check')){
  if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==text){console.error('Finance export model bundle is stale');process.exitCode=1;}
 }else fs.writeFileSync(output,text);
}
module.exports={generate,output};
